<p>Two definitions explain why the program is built this way. Appendix B describes quality assurance as "all those planned and systematic actions necessary to provide adequate confidence that a structure, system, or component will perform satisfactorily in service." NQA-1 ties that confidence to an item’s <strong>safety function</strong> — the performance required of an item or service to achieve safe and reliable use of nuclear energy and processing of nuclear material.</p>
<p>In both cases the confidence has to be demonstrable to someone who was not there. That is why documentation carries so much weight in nuclear work. A well-made weld with no record and a defective weld with no record look identical to an auditor a decade later, and only one of them can be defended.</p>
<h2><strong>How does NQA-1 relate to nuclear regulations and ASME construction codes?</strong></h2>
<p><strong>NQA-1 and Appendix B establish quality assurance requirements. ASME construction codes establish requirements for designing and constructing the equipment.</strong> They answer different questions. Satisfying one does not satisfy the other, and neither can be substituted for the other.</p>
<p>This is the distinction that causes the most trouble in nuclear procurement. It surfaces because four separate layers of requirement arrive in the same procurement package.</p>
