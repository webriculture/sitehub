  <div class="ht-wrap">
    <div class="px-sec-head">
      <div class="px-kicker">Frequently Asked Questions</div>
      <h2>Custom Fabrication FAQs</h2>
    </div>
    <div class="px-faq">
<details><summary>What is the difference between B31.1 and B31.3 piping?</summary><div class="a"><p>ASME B31.1 covers power piping (boiler external piping, steam systems in power plants); B31.3 covers process piping in chemical, petroleum, and related plants. Harris Thermal fabricates to both codes and holds the ASME “PP” stamp for power piping.</p></div></details>
<details><summary>What is a modular process skid?</summary><div class="a"><p>In general industry usage, a modular skid is a process system fit up on a frame in a fabricator’s shop and shipped as a unit rather than assembled piece by piece in the field, which reduces on-site installation time, labor cost, and schedule risk. What a skid includes varies with the project. Harris Thermal’s scope is the equipment we fabricate: vessels, heat exchangers, process piping, and the assemblies they are fit up into. Pumps, instrumentation, and controls are not part of our standard supply scope.</p></div></details>
<details><summary>Can you fabricate equipment when no standard design exists?</summary><div class="a"><p>Yes — that’s a specialty. From nuclear test equipment to wave generators and concept-design specialty equipment, Harris Thermal takes on projects that land outside what most fabricators consider normal, with in-house engineering to take your concept to a buildable design.</p></div></details>
<details><summary>What is hard facing and when is it needed?</summary><div class="a"><p>Hard facing is the application of wear-resistant material to component surfaces to extend service life in abrasive or high-wear applications — common in mining, slurry handling, and high-velocity flow services.</p></div></details>
<details><summary>Do you fabricate nuclear-qualified equipment?</summary><div class="a"><p>Yes. Harris Thermal operates an NQA-1 quality program for nuclear-grade fabrication, including nuclear test equipment — see our <a href="/nuclear/">NQA-1 nuclear page</a> for the program’s scope.</p></div></details>
