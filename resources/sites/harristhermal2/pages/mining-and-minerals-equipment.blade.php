  <div class="ht-wrap">
    <div class="px-sec-head px-reveal">
      <div class="px-kicker">FAQs</div>
      <h2>Mining and minerals equipment questions.</h2>
    </div>
    <div class="px-faq">
<details><summary>What equipment does Harris Thermal fabricate for mining and mineral processing?</summary><div class="a"><p>Autoclaves and pressure-leach vessels, ASME Section VIII pressure vessels, high-pressure specialty vessels, process and mixing vessels, shell-and-tube heat exchangers, condensers, heat exchangers for slurry and process cooling duty, cyclones, scrubber vessels, basket strainers where appropriate, evaporators, crystallizers, brine concentration equipment, and process and storage tanks.</p></div></details>
<details><summary>Can Harris Thermal fabricate autoclaves and pressure-leach vessels?</summary><div class="a"><p>Yes. High-pressure leaching and hydrometallurgical refining vessels for gold, copper and nickel service are a long-standing part of Harris Thermal's mining work. These are heavy-wall, high-pressure, often high-alloy or clad builds, and they are fabricated in our own shop under the design conditions and material requirements the process sets.</p></div></details>
<details><summary>What specialty alloys and clad construction are available for mineral processing?</summary><div class="a"><p>Carbon steel, stainless steels, duplex stainless, AL-6XN, Hastelloy, Inconel, Monel, titanium and other qualified specialty materials. Clad and explosion-bonded construction is available where a corrosion-resistant wetted surface over a structural carbon-steel backing suits the design — a common answer on heavy-wall autoclaves where solid alloy would be prohibitive.</p></div></details>
<details><summary>Can Harris Thermal fabricate equipment for lithium and brine concentration?</summary><div class="a"><p>Yes. Lithium brine concentration is an evaporation and crystallization duty, and Harris Thermal fabricates the evaporators, crystallizers, condensers, heat exchangers and vessels those circuits use. Material selection follows the chloride level, temperature and concentration of the specific brine.</p></div></details>
