<!-- ===== Intro ===== -->
<section class="px-block" style="padding-bottom:56px">
  <div class="ht-wrap">
    <div class="px-sec-head px-reveal" style="margin-bottom:0;max-width:860px">
      <div class="px-kicker">Treatment · Liquefaction · Low-Temperature Service</div>
      <h2>Custom equipment for LNG and cryogenic process applications.</h2>
      <p>The LNG process begins with pre-treatment of feed gas to remove impurities such as H₂S, CO₂, H₂O, mercury and heavier hydrocarbons, before cooling to cryogenic temperatures around −145 °C to −163 °C (−229 °F to −261 °F) for storage and transport.</p>
      <p>Harris Thermal has fabricated equipment for LNG producers, EPCs and OEMs across that chain — the ASME-code exchangers, columns, separators and vessels the process requires, including Lethal Service and Cyclic Service designs per ASME Section VIII.</p>
