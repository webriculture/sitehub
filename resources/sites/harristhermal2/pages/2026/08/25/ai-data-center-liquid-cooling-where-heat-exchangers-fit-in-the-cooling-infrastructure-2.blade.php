<p>The TCS is held roughly an order of magnitude tighter for two reasons. It wets microchannel cold plates with clearances measured in fractions of a millimeter, and a pinhole there lands water on energized silicon.</p>
<p>Filtration splits the same way. ASHRAE recommends an absolute TCS filter rating “7 to 10 times smaller than the finest channel dimension in the IT cooling equipment.” The facility strainer guideline is “35 to 40 mesh (or 500 to 400 μm).” Vertiv’s <a href="https://www.vertiv.com/4a2540/globalassets/shared/vertiv-coolchip-cdu-2300kw-data-sheet-sl-80005.pdf">CoolChip CDU data sheet</a> reflects the split: 500 µm primary, 25 or 50 µm secondary.</p>
<p>Treat the two loops as separate chemistry domains and the equipment questions organize themselves. Wetted materials, corrosion allowance, cleanability, and inspection access all get answered differently on either side of the same exchanger.</p>
