    <h1>How long does a shell and tube heat exchanger last?</h1>
    <div class="ht-date">Published June 10, 2026</div>
  </div>
</section>
<div class="ht-postwrap">
  <div class="ht-wrap">
    <article class="ht-article">
      <div class="ht-post-body">
<p>Ask a supplier how long a shell and tube heat exchanger will last and you&#8217;ll almost always get the same answer: &quot;20 to 25 years, depending on conditions.&quot; That answer is defensible and useless. It flattens a lifespan determined by dozens of engineering decisions into a single shrug. The real question is which decisions determine whether your unit reaches 15 years or 40. Those choices are made at spec time, during operation, and at the first sign of degradation.</p>
<p><strong>TL;DR</strong></p>
<ul>
<li>The 20–25 year range is a baseline, not a guarantee.</li>
<li>TEMA class, alloy, and tube gauge set the unit&#8217;s lifespan ceiling.</li>
<li>Corrosion, fouling, erosion, and thermal fatigue push service life below that ceiling.</li>
<li>Re-tube when the shell is sound and fewer than 20% of tubes have failed.</li>
<li>Tube wall thickness is your starting point for remaining service life.</li>
</ul>
<h2>What &quot;20 to 25 years&quot; actually tells you</h2>
<p>The 20–25 year estimate assumes carbon steel, moderate fouling, and process conditions that stay within the design envelope. It&#8217;s a fair baseline. Change one variable and the timeline shifts hard.</p>
<p>A carbon steel unit running high-chloride cooling water can show through-wall pitting in under five years. The same geometry fabricated in titanium, running clean distilled water, can still be in service at 40 years with minimal intervention. Engineering standards set the framework, but the variance is real and it&#8217;s driven by decisions the plant controls.</p>
<p>Engineers specify shell and tube heat exchangers according to ASME and <a href="/2026/05/13/what-is-a-tema-heat-exchanger/">TEMA heat exchanger classifications</a>: Class C (General), B (Chemical), and R (Refinery). Each class carries different construction margins, and those margins translate directly into service life differences.</p>
<h2>Design decisions at order time that set your ceiling</h2>
<p>Every specification choice made before a unit ships sets a physical ceiling on its service life. Maintenance helps a unit reach its ceiling, but the ceiling cannot be exceeded once the steel is cut.</p>
<h3>TEMA class and construction margins</h3>
<p>TEMA C is appropriate for industrial service with non-aggressive fluids. TEMA B is the standard for chemical process service. TEMA R is specified for refinery and petrochemical applications where equipment failure has safety and financial consequences.</p>
<p>The construction differences between classes are not cosmetic. TEMA R requires larger corrosion allowances on shell and channel components, tighter tolerances on tube-to-tubesheet joints, and more stringent inspection requirements. A plant manager who specs TEMA C on an application that warrants TEMA R has traded service life for a lower line item. That tradeoff shows up as a shorter first service interval, not a lower total cost.</p>
<p>API Standard 660 governs petroleum and petrochemical service. It adds requirements beyond TEMA R across design, materials, fabrication, and testing. For refinery applications, it is the floor, not the ceiling.</p>
<h3>Tube wall thickness and gauge selection</h3>
<p>Tube wall thickness (gauge) is the single most direct lever on lifespan in corrosive or erosive service. Thicker walls tolerate more metal loss before reaching the minimum thickness that triggers re-tubing or plugging.</p>
<p>A heavier gauge tube costs more per foot and reduces the heat transfer surface area slightly for a given shell diameter. In clean service, the thicker wall may be unnecessary. In service with chlorides, sulfur compounds, or abrasive particulates, specifying one gauge heavier than the minimum is insurance against failure.</p>
<h3>Alloy selection for your service chemistry</h3>
<p>Alloy selection is the most important lifespan decision and the one most frequently miscalculated. Carbon steel is economical and appropriate for many services. It is a poor choice for high-chloride water, acidic condensates, or any fluid with measurable sulfide content.</p>
<p>The industry has been moving steadily toward corrosion-resistant alloys (titanium, nickel-based alloys like Monel and Hastelloy, and duplex stainless steels) for this reason. A solid tubesheet in a large exchanger made from an exotic alloy can cost well into the six figures. One approach used in practice is explosion bonding: a thin layer of corrosion-resistant material fused to a carbon steel backing. It provides full surface protection at a fraction of a solid alloy forging&#8217;s cost.</p>
<p>A unit correctly specified for its service chemistry will outlast an under-specified one in the same process by decades.</p>
<h2>The four conditions that cut lifespan short</h2>
<p>Design sets the ceiling. These four mechanisms push service life below it.</p>
<ul>
<li>
<p><strong>Corrosion</strong> is the leading cause of premature failure. Pitting corrosion from chlorides and crevice corrosion under deposits are the most common modes. Galvanic corrosion occurs when dissimilar metals contact each other in the presence of an electrolyte. Correct material pairing prevents it. Each mechanism has a measurable precursor: wall thinning. Running NDE tube wall inspections every 18 to 24 months catches corrosion before the unit fails.</p>
</li>
<li>
<p><strong>Fouling-driven wall thinning</strong> is slower and more insidious than acute corrosion. Scale deposits on tube walls act as an insulator. Heat transfer drops, and the usual response is to run higher temperatures to meet duty. The elevated temperatures speed up further degradation. Put the fouling fluid on the tube side. Mechanical cleaning (hydro-blasting, brushing) is straightforward there. Cleaning shell-side fouling on a fixed-bundle unit means chemical circulation and limited mechanical access. Severe scaling often ends with a full bundle replacement.</p>
</li>
<li>
<p><strong>Erosion</strong> from particulate slurries moving at high velocity removes tube wall material at the inlet face and at the first baffle span. Unlike corrosion, erosion damage concentrates at entry points and is visible early. Reducing fluid velocity at the inlet, installing impingement plates, or specifying a harder tube alloy for the inlet bundle section are practical countermeasures.</p>
</li>
<li>
<p><strong>Thermal fatigue</strong> accumulates in batch processing or any application where the exchanger cycles repeatedly between heating and cooling states. Each temperature cycle creates differential expansion between the shell and tube bundle. In fixed-tubesheet designs, that stress has nowhere to go except into the tube-to-tubesheet joints. At 10,000 or more thermal cycles per year, tube-to-tubesheet joint failures arrive early. Floating-head or U-tube configurations absorb differential expansion without transmitting the stress to the joints. Either is the correct specification for high-cycle service.</p>
</li>
</ul>
<h2>Re-tubing vs. replacement: where the ROI calculation lives</h2>
<p>When a unit starts showing tube failures, the decision is re-tube or replace.</p>
<h3>When re-tubing wins</h3>
<p>Re-tubing is the right call when tube failures are isolated and the shell, channels, and nozzles are in sound condition. The practical threshold most engineers use: fewer than 15 to 20 percent of tubes plugged or failed, with NDE confirming the shell wall is within minimum thickness. At that point, re-tubing recovers full capacity at a fraction of replacement cost.</p>
<p>One caveat: re-tubing with the same tube specification as the original unit will produce the same lifespan from the same service conditions. If corrosion caused the failures, re-tubing with carbon steel replaces failed tubes with tubes that will fail on the same timeline. The re-tube is the right moment to upgrade tube alloy or wall thickness, because the labor cost is already committed.</p>
<h3>When replacement wins</h3>
<p>Replacement makes sense when:</p>
<ul>
<li>The shell shows weld-line cracking or deformation that cannot be repaired to code.</li>
<li>Nozzle geometry no longer matches the current process piping.</li>
<li>A re-rate shows the design no longer matches the current duty: different flow rates, temperatures, or fluid chemistry.</li>
<li>The tube bundle has exceeded roughly 40 percent plugging and remaining surface cannot meet process requirements.</li>
</ul>
<p>A re-rate compares the original design against current operating conditions and converts guesswork into a number. Without one, you are estimating remaining capacity without data.</p>
<h3>The role of NDE before committing money</h3>
<p>Committing to a repair path without wall-thickness data means spending money without knowing what you are buying. Any <a href="/repairs/">heat exchanger re-tubing and repair</a> job should start with NDE. Harris Thermal&#8217;s repair work covers re-tubing, weld repair, and emergency field work, and includes a Test and Evaluate service that runs NDE procedures before any repair scope is committed.</p>
<p>Harris Thermal fabricated vessels for the Hanford Waste Treatment and Immobilization Plant to <a href="https://www.energy.gov/em/articles/more-vessels-arrive-hanford-wtp">QL-1 standards for nuclear quality</a>, each weighing approximately 150,000 pounds and standing 32 feet tall, according to the U.S. Department of Energy. The same discipline for machining, welding, and testing used for those vessels carries into a re-tube job.</p>
<h2>Auditing what you already have</h2>
<p>Start with NDE wall-thickness measurement. If process duty has changed, follow with a re-rate. The repair-or-replace call comes after both.</p>
<p>A unit that has never been NDE-tested has unknown remaining life. The test converts that unknown into a number: current wall thickness minus minimum required thickness equals remaining corrosion allowance, which at the measured corrosion rate gives you a service life estimate.</p>
<p>Two additional inputs matter. First, pull the TEMA class and material specification from the equipment file. A unit built to TEMA C that now runs chemical or refinery duty may be outside its design margins. Tube walls can look fine while the design envelope no longer fits the process. Second, document any process changes since commissioning: new fluid compositions, higher temperatures, changed flow rates. Those changes are what the re-rate is comparing against.</p>
<p>Harris Thermal&#8217;s <a href="/harris-thermal-transfer-products-faqs/">heat exchanger maintenance best practices</a> documentation details what information to gather before engaging a fabricator for an audit or repair assessment. Over 140 years of fabrication work across nuclear, chemical, food processing, and energy sectors informs what a complete pre-audit data package looks like.</p>
<h2>Determining your heat exchanger&#8217;s remaining service life</h2>
<p>&quot;20 to 25 years, depending on conditions&quot; stops being a shrug once you know which conditions are yours to control. TEMA class, alloy selection, and tube gauge are fixed at order time. Choose them for your specific service chemistry, not the median case. Corrosion, fouling, erosion, and thermal fatigue each have measurable precursors; NDE monitoring catches them before they become failures. Re-tubing versus replacement is a calculation, not a judgment call, and it requires tube wall data.</p>
<p>If you do not know your current tube wall thickness, you do not know your remaining service life. That is the number to find first.</p>


<h2>FAQs about shell and tube heat exchanger</h2>

<h3>How often should I schedule NDE tube wall inspections?</h3>
<p>Standard practice for industrial service is every 18 to 24 months, though high-corrosion environments may require annual testing. Non-destructive evaluation (NDE) provides the precise wall thickness data needed to calculate the remaining corrosion allowance. Without these measurements, there is no reliable way to predict when a unit will reach its minimum required thickness.</p>


<h3>What is the cost difference between re-tubing and a full replacement?</h3>
<p>Re-tubing typically costs 40% to 60% of a new unit because it reuse the existing shell, channels, and nozzles. This approach is most effective when the shell is structurally sound and tube failures are below 20%. If the shell requires significant weld repair or the process duty has changed, the ROI often shifts toward full replacement.</p>


<h3>Can I upgrade a TEMA Class C unit to Class R in the field?</h3>
<p>Field upgrades from TEMA Class C to Class R are generally impractical because Class R requires larger corrosion allowances and tighter tolerances built into the original forgings. While you can upgrade tube materials or thickness during a re-tube, you cannot increase the physical thickness of the shell or tubesheets once the vessel is fabricated.</p>


<h3>How do I prevent water hammer during batch process transitions?</h3>
<p>Water hammer occurs when steam collapses rapidly as cooling water enters the shell, creating a vacuum. Practitioners often install vacuum breakers on the shell-side exit or implement a timed delay between closing steam valves and opening cooling lines. This allows condensate to evacuate fully, preventing the mechanical shock that leads to tube sheet cracks.</p>


<h3>Why is the &quot;dirtiest&quot; fluid usually placed on the tube side?</h3>
<p>Placing fouling-prone fluids on the tube side allows for straightforward mechanical cleaning via hydro-blasting or brushing. Cleaning the shell side of a fixed-bundle unit is significantly more difficult, often requiring aggressive chemical circulation. If heavy scaling occurs on the shell side, it frequently results in a complete bundle replacement rather than a successful cleaning.</p>

