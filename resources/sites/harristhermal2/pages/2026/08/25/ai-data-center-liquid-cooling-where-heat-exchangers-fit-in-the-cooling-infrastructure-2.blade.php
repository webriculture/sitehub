    <h1>AI data center liquid cooling: where heat exchangers fit in the cooling infrastructure</h1>
    <div class="ht-date">Published August 25, 2026</div>
  </div>
</section>
<div class="ht-postwrap">
  <div class="ht-wrap">
    <article class="ht-article">
      <div class="ht-post-body">
<p>A single high-density AI training rack can draw more than 100 kW. Uptime Institute puts the NVIDIA GB200 NVL72 at roughly <a href="https://journal.uptimeinstitute.com/density-choices-for-ai-training-are-increasingly-complex/">132 kW in a 19-inch frame</a> — about 100 kW to cold plates, with more than 25 kW still rejected to air.</p>
<p>The challenge does not end at the cold plate. That heat still has to cross two or three fluid circuits, several heat exchangers, and a heat rejection plant before it reaches the atmosphere, and every transfer costs temperature difference.</p>
<p><strong>TL;DR</strong></p>
<ul>
<li>
<p><strong>Air runs out around 40–50 kW per rack.</strong> ASHRAE puts airflow for such a rack at up to 5,000 cfm, with fan power alone reaching at least 5 kW in a 50 kW rack.</p>
</li>
<li>
<p><strong>The CDU is a chemistry boundary, not just a hydraulic one.</strong> ASHRAE holds technology cooling chloride under 5 ppm against under 50 ppm for facility water.</p>
</li>
<li>
<p><strong>Plate exchangers are the usual CDU selection.</strong> Liquid-to-liquid units are rated at 4–5°C (7–9°F) approach; the liquid-to-air equivalent at 15°C (27°F).</p>
</li>
<li>
<p><strong>Coolant temperature is spreading both ways.</strong> ASHRAE extended its technology cooling classes down to S-20, while NVIDIA designs its Rubin-generation rack loop to a 45°C supply point.</p>
</li>
</ul>
<p><strong>On this page:</strong> the density problem · the heat path · why the loops are separated · facility heat rejection · plate versus shell-and-tube · materials and water chemistry · reliability and future load · common mistakes · what to specify · FAQs</p>
<h2><strong>Why AI density moved cooling out of the server room</strong></h2>
<p>Air cooling did not stop working. It ran out of air. Beyond roughly 40–50 kW per rack, the airflow and fan power needed to move that heat stop being practical.</p>
<p>ASHRAE — the American Society of Heating, Refrigerating and Air-Conditioning Engineers — publishes widely used technical guidance for data center thermal environments through its Technical Committee 9.9. TC 9.9 put numbers on the boundary in <a href="https://www.ashrae.org/file%20library/technical%20resources/bookstore/emergence-and-expansion-of-liquid-cooling-in-mainstream-data-centers_wp.pdf"><em>Emergence and Expansion of Liquid Cooling in Mainstream Data Centers</em></a>. A 40 to 50 kW rack “could be up to 5000 cfm” of airflow, and “in a 50 kW rack, the fan power translates to be at least 5 kW.” That is ten percent of rack power spent moving air, before the chiller plant does anything.</p>
<p>The installed base sits well below that line. Uptime Institute reports modal rack densities <a href="https://journal.uptimeinstitute.com/lower-density-brings-server-efficiency-and-cooling-gains/">shifting toward 10 kW</a>, and puts the consensus for where direct liquid cooling becomes necessary or economically justified at 20–30 kW per rack.</p>
<p>AI clusters skip past that range. The ASHRAE, NEMA, and PNNL <a href="https://www.ashrae.org/technical-resources/ai-data-center-framework/energy-and-thermal-efficiency">AI Data Center Energy Performance Framework</a> describes GPU clusters driving “40–100 kW per rack vs.&nbsp;5–10 kW in legacy CPU racks.” It calls for a technology cooling system wherever densities “routinely exceed 50–120 kW per rack.”</p>
<p>Scale changes the character of the problem. Lawrence Berkeley National Laboratory’s <a href="https://eta.lbl.gov/publications/united-states-data-center-energy-2025">2025 update</a> puts 2024 U.S. data center electricity use at 192 TWh, reaching 649 TWh by 2030 in its reference case. Cooling systems and power distribution losses accounted for 31% of the 2024 total.</p>
<p>At those numbers, cooling stops being a room-conditioning exercise. It becomes a process heat-transfer system with a distributed load, a water balance, and a heat sink.</p>
<h2><strong>The heat path: TCS, FWS, and the exchanger between them</strong></h2>
<p>Heat leaving an AI processor follows a fixed chain: <strong>die → cold plate → technology cooling system → CDU heat exchanger → facility water system → heat rejection → atmosphere or reuse.</strong> Each interface costs temperature difference.</p>
<p><strong>Die to cold plate.</strong> The processor rejects heat through its lid into a cold plate with fine internal channels. Uptime reports Intel processors specified for liquid cooling with case temperatures <a href="https://journal.uptimeinstitute.com/performance-expectations-of-liquid-cooling-need-a-reality-check/">as low as 57°C (134.6°F)</a>. DRAM degrades above 85°C (185°F). Those two ceilings set everything upstream.</p>
<p><strong>Cold plate to technology cooling system.</strong> The TCS is the IT-side circuit: cold plates, rack manifolds, quick disconnects, and the piping serving a defined set of hardware. ASHRAE’s <a href="https://www.ashrae.org/file%20library/technical%20resources/bookstore/whitepaper_tc099-watercooledservers.pdf"><em>Water-Cooled Servers</em></a> describes it as “data-center-specific and most often associated with a specific set of IT hardware.”</p>
<p><strong>TCS to facility water system through the CDU.</strong> The coolant distribution unit holds the liquid-to-liquid heat exchanger that moves heat between the circuits, plus pumps, filtration, instrumentation, and controls. The same white paper lists six functions for it: transfer heat from TCS to FWS, circulate TCS coolant, permit a coolant other than water, prevent condensation, hold a coolant chemistry different from the FWS, and supply flexible coolant temperature.</p>
<p>That fourth function drives more CDU control logic than any efficiency target. The CDU “is responsible for monitoring the ambient dew point and elevating the secondary water loop (TCS) supply temperature to at least 3.6°F (2°C) above the room dew point to prevent condensation.” Condensate inside energized IT equipment is not a performance issue. It is a damage event. Designs that couple IT equipment directly to facility water inherit the same obligation at a loop far harder to hold above dew point.</p>
<p><strong>FWS to heat rejection.</strong> The facility water system is the building or campus circuit — “often a campus- or site-wide building system,” in that paper’s phrasing — running to chillers, towers, fluid coolers, or dry coolers.</p>
<p>Two conventions catch process engineers out. In ASHRAE’s usage, the <strong>primary</strong> side of the CDU exchanger is the facility water side and the <strong>secondary</strong> side is the technology cooling side. And two class systems govern different loops: <strong>W-classes</strong> describe facility water supply temperature, <strong>S-classes</strong> describe TCS supply temperature.</p>
<h3><strong>W-classes and S-classes: what each one governs</strong></h3>
<p>The facility water classes carry their upper limit in the name — W17, W27, W32, W40, W45, and W+ — each with a common minimum of 2°C (35.6°F). W32 means a facility water supply maximum of 89.6°F (32°C). The <a href="https://www.ashrae.org/File%20Library/Technical%20Resources/Bookstore/Supplemental%20Files/Therm-Gdlns-5th-R-E-RefCard.pdf">reference card</a> for ASHRAE’s <em>Thermal Guidelines for Data Processing Environments</em> lists a cooling tower rather than a chiller as the primary equipment from W32 upward.</p>
<p>S-classes are newer. ASHRAE <a href="https://tc0909.ashraetcs.org/">TC 9.9</a> rewrote its <em>Liquid Cooling Guidelines for Datacom Equipment Centers</em> to introduce “a new set of environmental classes (S Classes) for the supply temperature of the Technology Cooling System (TCS) coolant.”</p>
<p>The low end of that set was extended afterward. TC 9.9 members on the <a href="https://www.ashrae.org/news/ashraejournal/ashrae-journal-podcast-episode-49">ASHRAE Journal Podcast</a> in June 2025 said the range “which was S-30 to S-50 has expanded to S-20 to S-50,” with S-20 corresponding to 68°F (20°C).</p>
<p><strong>Read that as a widening spread, not a one-way trend.</strong> Some architectures need colder coolant at the chip; others are designed deliberately warm, and the warm end is where the facility economics live. The CDU exchanger sits between those objectives, and its approach temperature reconciles them. Uptime observes facility water temperatures “seem to be converging around 32°C (89.6°F)” in practice.</p>
<h2><strong>Why the loops are separated: chemistry, not just hydraulics</strong></h2>
<p>Most explanations of the CDU stop at pressure isolation. That is real, and it is the smaller half of the answer.</p>
<p>ASHRAE states the larger half plainly. The liquid-to-liquid heat exchanger between TCS and FWS “is able to provide a critical benefit to ITE: separation of water quality control domains.”</p>
