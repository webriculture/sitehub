<h2><strong>FAQs about liquid cooling for AI data centers</strong></h2>
<h3><strong>What is a coolant distribution unit, and what does it actually do?</strong></h3>
<p>A CDU is the interface between the IT-side technology cooling system and the building’s facility water system. It holds a liquid-to-liquid heat exchanger, pumps, filtration, and controls. ASHRAE credits it with six functions, of which two matter most: separating the two loops’ water chemistry, and holding TCS supply above the room dew point to prevent condensation.</p>
<h3><strong>What is the difference between the technology cooling system and the facility water system?</strong></h3>
<p>The TCS is the IT-side loop — cold plates, manifolds, and the piping serving specific hardware. The FWS is the building or campus loop feeding chillers, towers, and coolers. The distinction matters because their water chemistry requirements differ by roughly an order of magnitude, and ownership usually splits between facilities and IT at that boundary.</p>
<h3><strong>Why are plate heat exchangers commonly used inside CDUs?</strong></h3>
<p>Because the duty is a very close approach in a very small envelope, with clean filtered fluid on both sides. Corrugated plates produce high turbulence and high surface area per unit volume. ASHRAE describes CDU exchangers as flat plate construction with 2 to 8 mm plate spacing, and commercial liquid-to-liquid units are rated at 4–5°C (7–9°F) approach.</p>
<h3><strong>When might a shell-and-tube heat exchanger be used in data center cooling infrastructure?</strong></h3>
<p>Not inside the CDU. It becomes a candidate further out where a specific condition justifies it: ASME Section VIII stamped construction, pressures or temperatures outside plate and gasket envelopes, alloys unavailable in plate form, awkward geometry, or a service life built on mechanical cleaning and retubing. Otherwise gasketed plate equipment is usually the better answer.</p>
<h3><strong>What water chemistry considerations apply to data center liquid cooling?</strong></h3>
<p>The technology cooling loop is held far tighter than the facility loop, because it wets microchannel cold plates next to energized electronics. ASHRAE puts TCS chloride under 5 ppm against under 50 ppm for facility water, with a biocide required. Open facility loops concentrate chloride by evaporation, so a makeup water analysis is not a loop water analysis.</p>
<h3><strong>What are the ASHRAE W-classes and S-classes?</strong></h3>
<p>W-classes describe facility water supply temperature — W17 through W+, with a common minimum of 2°C (35.6°F). S-classes are newer and describe technology cooling supply temperature to the IT equipment. TC 9.9 members have confirmed the S-class range was extended down to S-20, or 68°F (20°C), because high-power processors need colder coolant at the chip.</p>

