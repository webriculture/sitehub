    <h1>What is the difference between a pressure vessel and a storage tank?</h1>
    <div class="ht-date">Published June 11, 2026</div>
  </div>
</section>
<div class="ht-postwrap">
  <div class="ht-wrap">
    <article class="ht-article">
      <div class="ht-post-body">
<p>The 15 PSI threshold looks like a line someone drew on a form. It isn&#8217;t. Below that pressure, a container failure releases fluid. Above it, a rupture releases pressurized fluid with enough stored mechanical energy to damage surrounding structure. That physics difference, not regulatory preference, created two separate engineering codes and two separate inspection regimes. The cost gap widens every year the equipment operates.</p>
<p><strong>TL;DR</strong></p>
<ul>
<li>The 15 PSI boundary marks a stored-energy threshold, not an administrative rule.</li>
<li>ASME Section VIII governs pressure vessels; API 650 and 620 govern storage tanks.</li>
<li>Head geometry, plate thickness, and weld qualification drive the fabrication cost gap.</li>
<li>Mandatory inspection cycles add substantial lifetime cost beyond the purchase price.</li>
<li>Fluid hazard and cyclic loading can require ASME certification even below 15 PSI.</li>
</ul>
<h2>The stored-energy boundary behind the 15 PSI rule</h2>
<p>Stored mechanical energy in a pressurized container scales with both pressure and internal volume. At atmospheric pressure, a breach opens and fluid escapes. The failure doesn&#8217;t just scale up. At elevated pressure, the same breach becomes a rupture: stored energy releases all at once, and the surrounding structure absorbs it.</p>
<p>ASME recognized the energy difference by codifying it. Containers designed for internal pressures above 15 PSI fall under the Boiler and Pressure Vessel Code (BPVC) Section VIII. Containers at or below 15 PSI fall under API standards. The codes were written separately because the engineering problems they address are separate.</p>
<p>Regulators enforce the energy-based logic in permitting. In California, Cal/OSHA requires permits for air tanks and LPG storage tanks over 125 gallons and for high-pressure boilers above 15 psig. The permit threshold is not administrative convenience. It marks the point at which stored energy becomes large enough that government oversight is considered non-negotiable.</p>
<h2>What ASME Section VIII and API 650/620 actually require</h2>
<p>The code a buyer specifies at procurement determines the fabrication pathway for every subsequent step.</p>
<h3>ASME Section VIII for pressure vessels</h3>
<p>ASME Section VIII mandates stress calculations for minimum wall thickness based on design pressure, operating temperature, and corrosion allowance. It prescribes head geometries to distribute that pressure load: torispherical (also called F&amp;D), ellipsoidal, and hemispherical. Each spreads the load across the head surface to avoid stress concentrations at the junction with the shell. The code requires qualified weld procedures and documented welder qualification records. It ends with a third-party inspection process and an ASME &quot;U&quot; stamp on the vessel nameplate. Without the stamp, the vessel does not legally meet the code.</p>
<h3>API 650 and API 620 for storage tanks</h3>
<p>API 650 governs welded tanks for oil storage at atmospheric pressure. It allows flat or conical bottoms and uses a thinner-plate, larger-diameter design philosophy built for volume, not pressure load. The head geometry question that governs vessel engineering does not arise under API 650 because the structural demands are different.</p>
<p>API 620 extends tank coverage into low-pressure applications up to 15 PSI, written for large-diameter storage. It addresses geometry and weld quality for storage service, not the fatigue-life and fluid-containment margins that ASME Section VIII requires for pressurized service.</p>
<h3>Why the code choice matters at procurement</h3>
<p>When a buyer changes the specified code after fabrication starts, the consequences go beyond a paperwork revision. It requires recalculating wall thickness, redesigning head geometry, requalifying weld procedures, and, in most cases, starting over on material procurement. Determine the code at the project&#8217;s start to ensure the correct plate steel is ordered.</p>
<h2>Wall thickness, head geometry, and where construction costs separate</h2>
<p>ASME Section VIII&#8217;s material and qualification requirements are where the fabrication cost gap opens up, not the design fee.</p>
<h3>Plate thickness and material escalation</h3>
<p>ASME Section VIII wall thickness calculations account for internal pressure, corrosion allowance, and material strength based on temperature. As operating pressure increases, minimum plate thickness increases. For carbon steel at modest pressure and temperature, the difference from an API 650 tank plate may be moderate. As service conditions escalate, the required material grade escalates with them.</p>
<p>Pressure vessel materials range from carbon steel and 304L/316L stainless through duplex stainless, AL-6XN, Hastelloy, Inconel, Monel, titanium, zirconium, and tantalum. Material selection is driven by operating temperature, operating pressure, and fluid corrosivity. Each step up the alloy ladder carries a substantial price increase per pound. Maximum allowable operating pressures for pressure vessels can reach 150,000 PSI. The wall thickness required at that range bears no relationship to anything API 650 or 620 addresses.</p>
<p>Storage tanks, operating at atmospheric or near-atmospheric conditions with non-aggressive fluids, are typically built from carbon steel or commodity stainless grades.</p>
<h3>Head geometry and weld qualification hours</h3>
<p>A torispherical or ellipsoidal head is a formed component. Fabricating it requires specialized forming equipment, dimensional inspection after forming, and fit-up to the shell that meets the tolerances ASME Section VIII specifies. Hemispherical heads are more demanding still, used at higher pressures where the stress distribution benefits justify the forming cost.</p>
<p>A flat-bottom storage tank does not require any of that. The bottom plate is cut, laid, and welded.</p>
<p>Weld qualification is where the labor cost difference becomes most visible. ASME Section VIII requires documented weld procedure specifications, procedure qualification records, and welder performance qualifications. Every weld that goes into a pressure vessel has a paper trail. The processes required (GMAW, GTAW, FCAW, and SAW) are performed by qualified welders whose certifications must be current and on file. When required by service conditions, post-weld heat treatment adds another step and another cost.</p>
<p>Storage tank welding under API 650 still demands skilled work, but the qualification burden is lower, and the labor hours reflect that.</p>
<h2>Inspection cycles and what they add to the lifetime cost</h2>
<p>A pressure vessel&#8217;s ASME &quot;U&quot; stamp is not a one-time credential. It commits the owner to a documented inspection history.</p>
<p>Periodic internal and external inspections, shell thickness measurements, and non-destructive examination (NDE) procedures are performed by National Board Commissioned Inspectors. Inspection frequency and scope depend on service conditions, fluid type, operating pressure, and jurisdiction. Over a vessel&#8217;s 20-to-30-year service life, those inspection events accumulate cost. The inspection schedule for a pressure vessel in continuous process service can amount to a substantial fraction of the original fabrication price.</p>
<p>API 650 storage tanks operate under less stringent inspection obligations. Routine visual checks and thickness measurements still apply, but the commissioned-inspector infrastructure does not.</p>
<p>Buyers who compare fabrication cost alone miss the full picture. The vessel costs more to build, and it costs more to operate, inspect, and maintain for its entire service life.</p>
<p>When vessels reach the end of their original service parameters, some can be re-evaluated through a formal re-rate process. Re-rating requires engineering review and code documentation. A non-code storage tank cannot be re-rated into pressure vessel service; it was never built to the documentation standard that re-rating requires.</p>
<h2>The API 620 gray zone: when pressure alone does not settle the question</h2>
<p>API 620 technically covers tanks operating up to 15 PSI, which overlaps the pressure vessel threshold. Some engineers treat it as the appropriate specification for any container at or near that pressure. For large-diameter, static, low-pressure storage of non-hazardous fluids, that&#8217;s correct. Its design methodology addresses geometry and weld quality for storage service. The standard breaks when the application involves cyclic loading or fluids classified as lethal under ASME Section VIII.</p>
<p>Cyclic service means repeated pressure or temperature cycling over the vessel&#8217;s operating life. Each cycle introduces fatigue loading at weld joints and discontinuities. ASME Section VIII addresses fatigue life; API 620 does not. Lethal-service fluids require containment margins and weld integrity requirements that the storage tank standard was not written to provide. An engineer who specifies API 620 for either condition has applied a standard whose scope excludes the failure modes that condition creates.</p>
<p>Harris Thermal engineers ASME-certified vessels for lethal-service and cyclic-service applications. Weld integrity and fatigue life requirements reflect the physics of those conditions, not a higher operating pressure alone. Their <a href="/liquefied-natural-gas-equipment/">LNG equipment</a> and <a href="/chemical-industry-equipment/">chemical industry vessels</a> are specified to ASME Section VIII, Division 1 based on fluid classification and loading profile. Operating pressure is one input, not the only one. The fluid and the service profile determine the code, and the code determines the fabrication standard.</p>
<h2>A practical decision framework: four questions before you specify</h2>
<p>Four questions settle the specification. If any of the first three pushes into ASME territory, the vessel&#8217;s cost premium is your lower-risk option.</p>
<ul>
<li>Will the container hold pressure above 15 PSI at any point, including upset conditions? ASME Section VIII applies.</li>
<li>Is the fluid classified as lethal under ASME UW-2? ASME Section VIII applies regardless of operating pressure.</li>
<li>Will the container undergo repeated pressure or temperature cycling, introducing fatigue loading at welds? ASME Section VIII applies regardless of operating pressure.</li>
<li>Does the total cost model include inspection schedule, NDE procedures, and commissioned inspector fees over the vessel&#8217;s 20-to-30-year life? If not, the cost comparison is incomplete.</li>
</ul>
<p>When all four conditions confirm atmospheric, non-lethal, static storage, a code-built or non-code storage tank is the appropriate choice. Harris Thermal fabricates both from a single in-house facility. Their <a href="/engineering/">mechanical design</a> runs under ASME Section VIII for vessels and API 650/620 for tanks, matched to whichever answers those four questions produce.</p>
<h2>Engineering calculations must drive the specification decision</h2>
<p>The 15 PSI boundary is not where the work ends. It is where it starts. Every requirement behind it exists because the stored energy in a pressurized container is real, and misspecification has real consequences. Harris Thermal builds <a href="/pressure-vessels-tanks/">custom pressure vessels and storage tanks</a> under whichever code the service conditions require, with no subcontractors between specification and finished weld. A buyer who under-specifies a pressure vessel as a storage tank creates documented liability. Over-specifying a tank as a vessel adds cost without adding risk. When the application is ambiguous, specify up.</p>


<h2>FAQs about pressure vessel vs storage tank</h2>

<h3>How does the cost of a pressure vessel compare to a storage tank at the same volume?</h3>
<p>A pressure vessel typically costs 2 to 4 times more than an atmospheric storage tank of equivalent volume. This gap is driven by thicker plate requirements, specialized head geometries like torispherical ends, and the labor hours required for ASME-qualified weld procedures and documentation.</p>


<h3>Can an existing storage tank be re-rated for pressurized service?</h3>
<p>No, a standard atmospheric storage tank cannot be re-rated for pressure because it lacks the necessary material certifications, head geometry, and weld paper trail required by <a href="/pressure-vessels-tanks/">ASME Section VIII</a>. While Harris Thermal can re-rate older pressure vessels for new conditions, a non-code tank was never built to the documentation standards that a formal re-rate process requires.</p>


<h3>What is the difference between API 620 and ASME Section VIII for low-pressure applications?</h3>
<p>API 620 governs large, welded tanks operating up to 15 PSI, while ASME Section VIII applies to vessels exceeding 15 PSI or those handling lethal fluids. Engineers often specify ASME Section VIII even below 15 PSI for <a href="/liquefied-natural-gas-equipment/">cyclic service applications</a> because API 620 does not account for the fatigue loading caused by repeated pressure and temperature fluctuations.</p>


<h3>How often do pressure vessels require inspection compared to storage tanks?</h3>
<p>Pressure vessels follow a mandatory, documented inspection schedule managed by National Board Commissioned Inspectors, often requiring internal exams every 5 to 10 years depending on service conditions. API 650 storage tanks generally operate under less stringent visual check requirements and do not require the same third-party commissioned-inspector infrastructure for routine maintenance.</p>


<h3>Why is vacuum collapse a risk when using a pressure vessel for storage?</h3>
<p>Pressure vessels are engineered to withstand internal force pushing outward, but they can be surprisingly vulnerable to external pressure if a vacuum forms during fluid discharge. Without specialized vacuum relief venting, a vessel designed for high internal pressure can implode, a failure mode that <a href="/engineering/">Harris Thermal</a> addresses during the mechanical design phase for both vessels and tanks.</p>

