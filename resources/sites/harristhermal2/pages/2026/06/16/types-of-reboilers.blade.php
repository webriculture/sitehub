    <h1>Types of reboilers: kettle, thermosiphon, and forced circulation explained</h1>
    <div class="ht-date">Published June 16, 2026</div>
  </div>
</section>
<div class="ht-postwrap">
  <div class="ht-wrap">
    <article class="ht-article">
      <div class="ht-post-body">
<p>Which reboiler type belongs on your column? Most engineers reach for &quot;vertical thermosyphon&quot; first. That answer works until the fluid is viscous or the pressure is near vacuum. It also fails when the plant layout lacks room for added skirt height. Those three conditions are common, not edge cases. Each one eliminates the default choice before the conversation starts.</p>
<p><strong>TL;DR</strong></p>
<ul>
<li>Vertical thermosyphons are the lowest-cost type but choke above 15% vapor quality.</li>
<li>Kettle reboilers are the standard for vacuum and high-vaporization service.</li>
<li>Forced circulation is the only viable type for viscous or solid-laden fluids.</li>
<li>Internal reboilers eliminate external piping but are capped by column diameter.</li>
<li>Four conditions drive selection: vapor quality, headroom, fouling factor, and operating pressure.</li>
</ul>
<h2>What a reboiler does and why the type matters</h2>
<p>Distillation columns rely on a reboiler at the base to supply heat. The reboiler vaporizes a portion of the column bottoms liquid. That vapor rises through the trays or packing above and drives vapor-liquid equilibrium. Without it, the column has no separation driving force.</p>
<p>The wrong type affects more than thermal efficiency. It changes fouling rate, required column height, process control behavior, and capital cost. These design decisions define the column&#8217;s operating life, not minor commissioning adjustments.</p>
<p>Four factors drive the choice: fluid nature (viscosity and fouling tendency), operating pressure, equipment layout (available headroom), and required vaporization rate, according to <a href="https://www.klmtechgroup.com/PDF/EDG-SYS/ENGINEERING-DESIGN-GUIDELINES-reboiler-Rev1.3web.pdf">KLM Technology Group guidelines</a>. Engineers need to evaluate all four before selecting a type.</p>
<h2>Kettle reboilers: reliable across pressure extremes</h2>
<p>A kettle reboiler uses a TEMA K-shell, a horizontal shell with a tube bundle inside. The column bottoms liquid fills the shell and boils on the tube surfaces (shell-side boiling). The vapor space above the bundle lets vapor and liquid disengage. The vapor return line then sends product back to the column. That separation space is why the K-shell is physically larger and more expensive than other shell types.</p>
<p>Kettle reboilers contribute one theoretical tray to the distillation process. Designers should include this in column calculations.</p>
<p>The defining characteristic is low liquid circulation rate. Liquid enters the shell under head pressure or via pump, sits in a quiescent pool, and boils off. That low circulation is both the type&#8217;s strength and its weakness. Low circulation and horizontal configuration make kettle reboilers insensitive to system hydraulics, according to <a href="https://www.sciencedirect.com/topics/engineering/kettle-reboiler">ScienceDirect</a>. They stay reliable at vacuum and near-critical pressures where thermosyphons often face operational problems.</p>
<p>The trade-off is fouling. Low velocity lets solids and deposits build on tube surfaces faster than in high-velocity designs. A kettle is the standard choice for clean, low-pressure services with high vaporization requirements. If the service fouls easily, low circulation accelerates deposit buildup throughout the run.</p>
<h2>Thermosyphon reboilers: vertical and horizontal configurations</h2>
<p>Thermosyphon reboilers generate circulation without a pump. The density difference between the cooler liquid entering the exchanger and the lighter two-phase mixture leaving it creates a pressure gradient that drives continuous flow. The mechanism is inexpensive, but physics constrains it in ways that matter for column design.</p>
<h3>Vertical thermosyphon reboilers</h3>
<p>In a vertical thermosyphon, liquid enters the bottom of vertical tubes. Boiling occurs inside the tubes (tube-side), and the two-phase mixture rises to the top and discharges back to the column. High tube velocity keeps the tube walls clean. Vertical thermosyphons are the most affordable industrial reboiler type, according to <a href="https://processphase.com/reboiler-selection-essentials/">Process Phase</a>. They need no upstream pump, resist fouling at high tube velocity, and mount directly against the column.</p>
<p>The governing constraint is vapor quality at the outlet. The optimum should not exceed 15%. Above that threshold, the two-phase flow regime inside the tubes shifts from annular flow toward slug flow and eventually chokes, collapsing circulation. A <a href="https://www.sciencedirect.com/science/article/abs/pii/S026387620800021X">ScienceDirect study</a> confirms that vertical thermosyphons provide high heat transfer rates, simple construction, and low costs. Those advantages exist only within the vapor quality window.</p>
<p>Vertical thermosyphons also require column skirt height. The reboiler mounts below the column. The driving head for natural circulation depends on the liquid level difference between the column sump and the reboiler outlet. Plants with constrained plot space or short column skirts cannot always accommodate this.</p>
<h3>Horizontal thermosyphon reboilers</h3>
<p>A horizontal thermosyphon passes liquid across a tube bundle in cross-flow, with boiling occurring on the shell side. Natural circulation is preserved, but the horizontal orientation reduces the skirt height demand. Horizontal types can also handle outlet vapor quality up to around 25%, compared to the 15% ceiling for vertical designs.</p>
<p>The cross-flow geometry introduces more uncertainty in predicting shell-side heat transfer rates than the vertical tube-side configuration does, according to <a href="https://www.thermopedia.com/content/1078/">Thermopedia</a>. Fouling is also harder to predict, and fouling risk is higher.</p>
<p>Vertical thermosyphons are often treated as the default because they cost less. That reasoning holds only when skirt height is available and outlet vapor quality stays below 15%. At higher vaporization rates, two-phase flow chokes inside the tubes and circulation collapses. In height-constrained plants, or in services requiring more than 15% vapor quality, a vertical thermosyphon does not save money. It produces a column that underperforms or needs retrofit. Engineers should evaluate the horizontal configuration or kettle before committing the vertical type to the layout.</p>
<h2>Forced circulation reboilers: when the fluid will not move on its own</h2>
<p>Natural circulation requires a fluid that can form a density gradient when heated. High-viscosity liquids, slurries, and fluids carrying solids resist or prevent this. A forced circulation reboiler replaces the density-driven flow mechanism with a pump. The pump pushes liquid through the heat exchanger at a controlled rate, independent of fluid properties.</p>
<p>Pump-driven control is the defining advantage of forced circulation. Circulation rate is adjustable regardless of viscosity, fouling factor, or vapor quality. For fluids where a thermosyphon would stall and a kettle would foul rapidly, forced circulation keeps the tubes clean and the process running.</p>
<p>Forced circulation is the highest-cost reboiler type, adding a pump, motor, and extra piping on top of the exchanger itself, according to <a href="https://www.aidic.it/cet/09/18/134.pdf">Chemical Engineering Transactions (AIDIC)</a>. Operating costs run higher too, because the pump never stops. That premium is justified only when the fluid demands it.</p>
<p>Forced circulation should not be the default for low-viscosity services. The pump adds a failure mode, and the capital cost is difficult to recover on simple duties.</p>
<h2>Internal reboilers: simplest design, hardest constraint</h2>
<p>An internal reboiler mounts the tube bundle directly inside the distillation column&#8217;s sump, eliminating the external shell and all connecting piping. No separate vessel, no return line, no extra plot space. The footprint advantage is real, but so is the physical limit: the bundle cannot exceed the column diameter, which caps the available heat transfer area, as <a href="https://www.thermopedia.com/content/1078/">Thermopedia documents</a>. Maintenance requires column entry, creating access and turnaround scheduling challenges that external types don&#8217;t impose.</p>
<p>Internal reboilers appear in practice where those limitations are acceptable trade-offs. Plate-fin exchangers are commonly used as internal reboilers in distillation towers for air separation. The compact geometry and cryogenic operating environment make the internal configuration practical in that context. Outside of specialized applications with constrained footprints and small heat duties, maintenance access concerns generally favor external configurations.</p>
<h2>Matching reboiler type to process conditions</h2>
<ul>
<li>Fouling fluids favor a vertical thermosyphon. High tube velocity resists deposit buildup. Use forced circulation when viscosity also prevents natural flow.</li>
<li>High-viscosity or solids-containing fluids require forced circulation or kettle. Use forced circulation if precise flow control matters; kettle works when viscosity is moderate and fouling risk is manageable.</li>
<li>Vacuum service is best handled by a kettle. Thermosyphons are sensitive to hydraulic instability at low pressure; the kettle&#8217;s low-circulation design is not.</li>
<li>Limited headroom rules out vertical thermosyphons. A horizontal thermosyphon or kettle fits within shorter column skirts.</li>
<li>Vapor quality above 15% exceeds the vertical thermosyphon&#8217;s limit. Horizontal thermosyphons handle up to 25%; kettles handle higher still.</li>
<li>Clean fluid with adequate skirt height and a tight budget: vertical thermosyphon is the lowest capital and operating cost option.</li>
<li>Small duty with sufficient column diameter: an internal reboiler eliminates external vessels and piping entirely.</li>
</ul>
<p>Reboiler type also determines the TEMA service classification for the mechanical design. Harris Thermal builds to <a href="/resources/">TEMA C, TEMA B, and TEMA R service standards</a>, the three classifications that govern reboiler mechanical design across process industries. The specific service class affects material selection, tube bundle design, and inspection requirements. Those decisions connect directly to the type and process conditions above. For more on how TEMA classifications work, see <a href="/2026/05/13/what-is-a-tema-heat-exchanger/">TEMA heat exchanger classifications</a>.</p>
<p>Reboiler type selection is one part of sizing the full distillation train. <a href="/chemical-industry-equipment/">Reboilers and overhead condensers</a> set the vapor-liquid balance across the column together. Specify one without the other and the system is difficult to control at design conditions.</p>
<h2>Start with the default, then eliminate</h2>
<p>The vertical thermosyphon is the starting point: lowest cost, no pump, low fouling at high tube velocity. Run it against four conditions before committing. Does the outlet vapor quality exceed 15%? Does the column skirt height support the required driving head? Does the process fluid&#8217;s viscosity or solids content prevent natural circulation? Is the operating pressure near vacuum or near the fluid&#8217;s critical point? Each &quot;yes&quot; eliminates the vertical thermosyphon and points toward one of the remaining types. Kettle for pressure extremes and high vaporization. Horizontal thermosyphon for height constraints with moderate vaporization. Forced circulation when the fluid will not move on its own. The engineer who works through those four questions has made a type selection, not assumed one.</p>


<h2>FAQs about types of reboilers</h2>

<h3>What happens if a vertical thermosyphon exceeds 15% vapor quality?</h3>
<p>Exceeding the 15% vapor quality limit causes the internal flow regime to shift from stable annular flow toward slug flow. This transition increases pressure drop and can lead to flow choking, which collapses natural circulation. According to <a href="https://processphase.com/reboiler-selection-essentials/">Process Phase</a>, staying below this threshold is necessary to maintain the density gradient that drives the system without a pump.</p>


<h3>How does a TEMA K-shell differ from an E-shell in reboiler service?</h3>
<p>The TEMA K-shell, or kettle reboiler, features an enlarged shell section above the tube bundle to facilitate vapor-liquid disengagement. In contrast, a standard E-shell is a basic shell-and-tube design used for thermosyphons where separation occurs back in the distillation column. The K-shell acts as a surge vessel and provides one theoretical tray for the process (<a href="https://www.sciencedirect.com/topics/engineering/kettle-reboiler">ScienceDirect</a>).</p>


<h3>Which reboiler type is best for vacuum distillation?</h3>
<p>Kettle reboilers are the standard for vacuum service because they are relatively insensitive to system hydraulics. Thermosyphons often struggle at low pressures due to hydraulic instability and the difficulty of maintaining a consistent driving head. The kettle&#8217;s horizontal configuration and quiescent boiling pool ensure reliable operation near vacuum or near-critical points (<a href="https://www.sciencedirect.com/topics/engineering/kettle-reboiler">ScienceDirect</a>).</p>


<h3>Why are internal reboilers rarely used in large-scale chemical plants?</h3>
<p>Internal reboilers are physically limited by the distillation column diameter, which caps the available heat transfer area. Maintenance is a significant drawback, as cleaning or repairing the bundle requires a full column shutdown and entry. While they save plot space, practitioners generally prefer external units like those manufactured by <a href="/shell-and-tube-heat-exchangers/">Harris Thermal</a> for easier bundle access and maintenance.</p>


<h3>When is forced circulation more cost-effective than a thermosyphon?</h3>
<p>Forced circulation becomes cost-effective when process fluids are highly viscous or contain solids that would cause a thermosyphon to stall or foul rapidly. Although the capital cost is higher due to the pump and motor, the controlled velocity prevents frequent shutdowns for cleaning. <a href="https://www.aidic.it/cet/09/18/134.pdf">Chemical Engineering Transactions</a> notes that this precise circulation control justifies the premium in difficult services.</p>

