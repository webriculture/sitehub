      <div class="px-kicker">Our Heritage</div>
      <h2>From Harris Ice Machine Works to global fabricator.</h2>
      <p>For more than 140 years, Harris Thermal has proudly manufactured equipment in the United States. Originally founded as <strong>Harris Ice Machine Works</strong>, the company built ammonia-refrigeration equipment before transitioning during the world war era into custom thermal process equipment — first supporting the United States' war efforts, then the rapid expansion of American manufacturing.</p>
      <p>That spirit of innovation carries forward today. We build some of the largest custom vessels in the industry — over 500,000 pounds — and ship equipment to clients around the globe. This heritage proves our ability to adapt, endure, and deliver value for generations of customers.</p>
