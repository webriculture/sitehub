<section class="px-block soft" id="faq">
  <div class="ht-wrap">
    <div class="px-sec-head">
      <div class="px-kicker">Frequently Asked Questions</div>
      <h2>Pressure Vessel &amp; Tank FAQs</h2>
    </div>
    <div class="px-faq">
<details><summary>What does the ASME U stamp mean on a pressure vessel?</summary><div class="a"><p>The U stamp certifies that a vessel was designed, fabricated, inspected, and tested in accordance with ASME Section VIII, Division 1, under a quality program audited by ASME, with an Authorized Inspector signing off. Harris Thermal holds the U stamp for new vessels and the R stamp for repairs and alterations.</p></div></details>
<details><summary>When is an ASME code pressure vessel required?</summary><div class="a"><p>In general, vessels operating above 15 psi are subject to ASME Boiler and Pressure Vessel Code requirements in most U.S. jurisdictions. Storage tanks at atmospheric pressure typically fall under API 620/650 instead. Requirements vary by state and application &mdash; our quality team can help you determine what your jurisdiction requires.</p></div></details>
<details><summary>What is the difference between a pressure vessel and a storage tank?</summary><div class="a"><p>A pressure vessel is designed to contain fluids above 15 psi and falls under ASME Section VIII; a storage tank operates at or near atmospheric pressure and is typically built to API 620 or API 650. Harris Thermal fabricates both, including single-walled, double-walled, vertical, and horizontal tanks.</p></div></details>
<details><summary>How large a pressure vessel can you fabricate?</summary><div class="a"><p>Our Newberg, Oregon facility fabricates vessels and tanks over 500,000 pounds, with 200,000 pounds of overhead lifting capacity, 30 ft &times; 60 ft bay doors, and machining up to 16.5 ft in diameter. We have shipped 20 ft OD stainless steel tanks and routinely handle equipment most shops cannot.</p></div></details>
<details><summary>Can you build vessels for corrosive or lethal service?</summary><div class="a"><p>Yes. We fabricate in duplex, high-nickel alloys, titanium, and zirconium for corrosive service, and provide Lethal Service and Cyclic Service designs per ASME Section VIII, Division 1, including fatigue life and weld integrity analysis.</p></div></details>
<details><summary>Do you ship pressure vessels nationwide?</summary><div class="a"><p>Yes &mdash; worldwide. Our dedicated shipping department manages logistics with our own trucks and trailers, a 75-ton yard gantry crane, and experience shipping by truck and barge, including nitrogen purging and shrink wrapping for transport or long-term storage.</p></div></details>
