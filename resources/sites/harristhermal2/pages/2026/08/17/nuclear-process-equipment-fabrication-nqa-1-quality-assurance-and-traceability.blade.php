<p><em>Per RG 1.26, Revision 6, Table 1. Group D piping and valves are assigned to ASME B31.1; Group D atmospheric tanks to API 650, AWWA D-100, or ASME B96.1; and Group D tanks from 0 to 15 psi to API 620.</em></p>
<h3><strong>Where fabricated process equipment fits</strong></h3>
<p>RG 1.26 names the equipment types directly. Its Group B and Group C positions both apply to "pressure vessels, heat exchangers (other than turbines and condensers), storage tanks, piping, pumps, and valves" meeting the respective criteria.</p>
<p>Shell-and-tube exchangers, tanks, columns, condensers, evaporators, and separators all sit inside this framework somewhere. Where each one lands depends on its function, not its equipment category.</p>
<p>The Group D row is the practical opening for a great deal of fabricated process equipment, because a Section VIII, Division 1 vessel is an NRC-acceptable standard there. Owners may also impose selected NQA-1 requirements on non-safety-related scope by contract, including document control, material traceability, and records. That is why the inquiry documents, rather than the equipment type, determine what a fabricator actually has to do.</p>
<h2><strong>What changes in the shop under an applicable NQA-1 program?</strong></h2>
<p>Conventional ASME Code fabrication is already tightly controlled. Section VIII, Division 1 construction runs on a written quality control system reviewed by an Authorized Inspector. It requires procedures and welders qualified under Section IX, material certified to Section II specifications, examination by qualified NDE personnel, and a witnessed hydrostatic test before stamping.</p>
