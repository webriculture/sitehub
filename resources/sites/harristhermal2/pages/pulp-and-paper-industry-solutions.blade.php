<details><summary>Can Harris Thermal fabricate replacement equipment for an existing mill?</summary><div class="a"><p>Yes, and it is a large part of the pulp and paper work. Replacement heat exchangers built to existing envelope and nozzle geometry, replacement tube bundles for sound shells, vessels, and evaporator components built around the interfaces already in the mill. We work from existing drawings, field measurements or reverse-engineered specifications.</p></div></details>
<details><summary>What equipment does Harris Thermal fabricate for pulp and paper mills?</summary><div class="a"><p>Black-liquor evaporators, falling-film and multi-effect evaporator equipment, condensers, shell-and-tube heat exchangers, replacement bundles, digesters, ASME pressure vessels, columns and towers, cyclones, washer vessels, and mixing vessels and tanks.</p></div></details>
<details><summary>What equipment does Harris Thermal build for black liquor service?</summary><div class="a"><p>Harris Thermal fabricates evaporator and heat-transfer equipment used in black-liquor concentration and chemical-recovery applications, along with the condensers, exchangers and vessels that run with them. Black liquor is a scaling, corrosive, increasingly viscous stream, so material selection and evaporator configuration follow where in the concentration train the equipment sits.</p></div></details>
