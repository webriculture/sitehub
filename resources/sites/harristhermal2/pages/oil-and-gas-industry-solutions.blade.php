<section class="px-block soft" id="faqs">
  <div class="ht-wrap">
    <div class="px-sec-head px-reveal">
      <div class="px-kicker">FAQs</div>
      <h2>Oil and gas equipment questions.</h2>
    </div>
    <div class="px-faq">
<details><summary>What equipment does Harris Thermal fabricate for oil and gas?</summary><div class="a"><p>Shell-and-tube heat exchangers, process coolers and heaters, condensers, reboilers, replacement exchangers and tube bundles, ASME Section VIII pressure vessels, separators, knockout drums, accumulators, process vessels, columns and towers, scrubber vessels, cyclones, custom tanks, skid-mounted fabricated equipment within our scope, and high-alloy equipment for corrosive service.</p></div></details>
<details><summary>Can Harris Thermal fabricate replacement exchangers and tube bundles?</summary><div class="a"><p>Yes. Replacement exchangers can be built to the original envelope and nozzle geometry so the unit drops into existing piping and supports, re-tubed where the shell is sound, or re-rated for a duty above the original basis. We work from existing drawings, field measurements or reverse-engineered specifications. Existing drawings, the current duty and the duty now required are the useful starting point.</p></div></details>
<details><summary>Does Harris Thermal build shell-and-tube exchangers to TEMA?</summary><div class="a"><p>Yes. Harris Thermal can design and fabricate to applicable TEMA and ASME Section VIII, Division 1 requirements based on project scope, including TEMA Class R, C and B and API 660 where the specification calls for it. TEMA class is a mechanical robustness decision rather than a quality one, and over-specifying it adds cost without adding service life.</p></div></details>
<details><summary>What materials can Harris Thermal fabricate for corrosive oil and gas service?</summary><div class="a"><p>Carbon steel, stainless steels, duplex stainless, AL-6XN, high-nickel alloys, titanium and clad construction. Clad and explosion-bonded materials are available where a corrosion-resistant wetted surface over a structural carbon-steel backing suits the design. Selection follows the actual service conditions, including sour and high-chloride duty, rather than the nominal ones.</p></div></details>
