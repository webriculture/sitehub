      <h2>Black liquor evaporation &amp; concentration.</h2>
      <p>Harris Thermal fabricates evaporator and heat-transfer equipment used in black-liquor concentration and chemical-recovery applications.</p>
      <p>The stream gets more viscous, more scaling and more corrosive as it concentrates, so the material and the evaporator configuration follow where in the train the equipment sits. Our article on <a href="/2026/06/09/types-of-industrial-evaporators-and-how-to-choose/">choosing an industrial evaporator</a> works through that decision.</p>
      <ul class="px-checks">
        <li>Stainless and duplex for corrosion and chloride resistance</li>
        <li>Hastelloy, Inconel, Monel and AL-6XN where required</li>
        <li>ASME Section VIII construction</li>
        <li>TEMA-compliant exchangers</li>
      </ul>
