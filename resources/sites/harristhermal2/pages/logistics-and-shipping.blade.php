      <div class="px-kicker">Shipment Coordination</div>
      <h2>Planned as carefully as it is fabricated.</h2>
      <p>Custom-fabricated process equipment often requires transportation planning beyond a standard shipment. Harris Thermal coordinates transportation requirements with appropriate carriers, customers, and project stakeholders, taking equipment dimensions, weight, site access, delivery requirements, and project schedules into account.</p>
      <p>Because the equipment is designed and built here, its dimensions and shipping weight are known well before it is ready to leave — so the transportation requirements are identified while there is still time to plan around them, rather than discovered on the day it ships.</p>
      <p>In-house packaging includes shrink wrapping and nitrogen purging of vessels prior to shipment or for long-term storage — so your equipment arrives exactly as it left our floor.</p>
