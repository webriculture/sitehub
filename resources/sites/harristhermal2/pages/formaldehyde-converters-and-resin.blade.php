<section class="px-block soft" id="faqs">
  <div class="ht-wrap">
    <div class="px-sec-head px-reveal">
      <div class="px-kicker">FAQs</div>
      <h2>Formaldehyde and resin equipment questions.</h2>
    </div>
    <div class="px-faq">
<details><summary>What equipment does Harris Thermal fabricate for formaldehyde and resin processing?</summary><div class="a"><p>Formaldehyde converters and reactors, shell-and-tube heat exchangers, condensers, absorber and process columns, evaporators, scrubber vessels, crystallizers, ASME Section VIII pressure vessels, and storage and mixing tanks. Harris Thermal fabricates equipment to the process design provided by the producer, EPC or process licensor; it does not supply the process technology or a complete production plant.</p></div></details>
<details><summary>What is a formaldehyde converter?</summary><div class="a"><p>The converter is the reactor where methanol is converted to formaldehyde over a catalyst. It is a heat-transfer-intensive vessel: the reaction is strongly exothermic, so the converter has to remove heat while holding the catalyst at the temperature the process requires. That combination — reactor duty and heat exchanger duty in one fabricated unit — is why converters are built as custom equipment rather than selected from a catalog.</p></div></details>
<details><summary>Can Harris Thermal fabricate equipment for different formaldehyde process technologies?</summary><div class="a"><p>Harris Thermal fabricates converters and associated equipment to the customer, EPC or process-licensor requirements supplied for the project. Converter configuration, metallurgy, tube geometry and thermal requirements vary by process technology, and the design basis comes from the party that owns the process. Send the specification and our engineers will work through the fabrication and material requirements with you.</p></div></details>
<details><summary>What materials are available for formaldehyde and resin service?</summary><div class="a"><p>Stainless steels, duplex stainless, carbon steel and high-nickel alloys, with other qualified specialty materials available where the service requires them. Selection follows the stream, temperature and corrosion conditions defined in the process specification. See our materials and metallurgy capability for the full range.</p></div></details>
