      <h2>One platform, many specialized designs.</h2>
      <p>From evaporators to kettle reboilers, we fabricate the full family of shell-and-tube equipment in a wide variety of configurations and materials.</p>
    </div>
    <div class="px-types">
      <div class="px-type px-reveal">
        <div class="ico"><svg viewBox="0 0 24 24"><path d="M4 4h16v3H4zM4 10.5h16v3H4zM4 17h16v3H4z"/></svg></div>
        <h3>Evaporators &amp; Crystallization Plants</h3>
        <p>Whenever water or solvent must be removed, concentration increased, or pure crystals produced, our custom evaporators and crystallizers meet the most exacting process requirements — in all configurations and sizes.</p>
      </div>
      <div class="px-type px-reveal">
        <div class="ico"><svg viewBox="0 0 24 24"><path d="M12 2 6 12h4v10l6-12h-4z"/></svg></div>
        <h3>Falling Film Evaporators</h3>
        <p>The most widely used evaporator in the process industry. These brine concentrators deliver efficient heat transfer, high-purity distillate, and water recovery greater than 90% — driven by mechanical vapor recompression (MVR) or live steam.</p>
      </div>
      <div class="px-type px-reveal">
        <div class="ico"><svg viewBox="0 0 24 24"><path d="M12 2l9 5v10l-9 5-9-5V7zm0 2.3L5 8.2v7.6l7 3.9 7-3.9V8.2z"/></svg></div>
        <h3>Crystallizers</h3>
        <p>Meet stringent zero liquid discharge (ZLD) requirements by concentrating brine into clean water and solid salt crystals — with dissolved salts sometimes recovered as valuable by-products.</p>
      </div>
      <div class="px-type px-reveal">
        <div class="ico"><svg viewBox="0 0 24 24"><path d="M7 2h10v4l-3 3v13h-4V9L7 6z"/></svg></div>
        <h3>Formaldehyde Converters</h3>
        <p>Formaldehyde is a key raw material for melamine, urea-formaldehyde, and phenolic resins. We have fabricated formaldehyde converters for both silver-catalyst and Formox processes for many years.</p>
      </div>
      <div class="px-type px-reveal">
        <div class="ico"><svg viewBox="0 0 24 24"><path d="M3 18c2-1 4-1 6 0s4 1 6 0 4-1 6 0v3c-2-1-4-1-6 0s-4 1-6 0-4-1-6 0zm2-14h14l-2 10H7z"/></svg></div>
        <h3>Fry Oil Heaters</h3>
        <p>Harris Thermal supplies heat exchangers to the potato processing industry — efficient, easy-to-maintain systems for both frying and blanching, delivering maximum production with minimum waste.</p>
      </div>
      <div class="px-type px-reveal">
        <div class="ico"><svg viewBox="0 0 24 24"><path d="M4 8h13a3 3 0 0 1 0 6H4zm0 8h16v2H4zM4 4h16v2H4z"/></svg></div>
        <h3>Kettle Reboilers</h3>
        <p>Simple and reliable, kettle reboilers handle vaporization of up to 80% and are easy to maintain thanks to a removable tube bundle — with an overflow weir keeping the bundle covered for consistent operation.</p>
