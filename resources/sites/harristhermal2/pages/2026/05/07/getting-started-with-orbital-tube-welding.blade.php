    <h1>Getting started with orbital tube welding</h1>
    <div class="ht-date">Published May 7, 2026</div>
  </div>
</section>
<div class="ht-postwrap">
  <div class="ht-wrap">
    <article class="ht-article">
      <div class="ht-post-body">
<p>&quot;Push-button&quot; factory auto-programs are a myth. You usually have to manually adjust amps and triple pre-purge times just to get a clean weld. For years, fabricators relied on manual GTAW or factory-programmed orbital welders for simple tube joins. But as industries demand thicker walls, tighter metallurgical tolerances, and larger assemblies, these baseline setups fail.</p>
<p><strong>TL;DR</strong></p>
<ul>
<li>Autogenous orbital welding hits a hard structural limit at wall thicknesses of 0.16 inches.</li>
<li>Low-sulfur stainless steel triggers the Marangoni effect, widening beads by 50% and demanding heavy heat compensation.</li>
<li>Factory auto-programs require manual amperage tweaks and extended pre-purge times to prevent oxidation.</li>
<li>X-ray testing cannot reliably detect microscopic cracks in tube walls under 0.107 inches thick.</li>
</ul>
<h2>Phase 1: Baselining metallurgical constraints and limits</h2>
<h3>The structural limits of autogenous joins</h3>
<p>Before turning on the machine, evaluate the physical limits of the material. The American Welding Society projects a shortage of skilled manual welders, pushing teams toward automation. The case for autogenous (fusion-only) orbital welding is strong for high-purity sanitary lines. But it breaks when wall thickness exceeds <a href="https://www.swagelok.com/-/media/Distributor-Media/O-S/OKWT/Services/Orbital-Welding-in-Critical-Systems.ashx?la=en&amp;hash=23889DAF6D29F09FD74656B1FBC48E63BFE3F142">0.16 inches</a>. Past this 4mm threshold, autogenous welding cannot achieve full penetration. You also hit a wall with extreme heat-sink materials like copper, which draw thermal energy away from the joint too quickly. In these conditions, manual GTAW or automated filler-wire setups remain the only viable options.</p>
<p>Automated welding removes your ability to compensate for poor fit-up. You must face and square every tube end perfectly. Even microscopic burrs or slight gaps cause a rejected weld when no filler metal bridges the void.</p>
<h3>Managing the Marangoni effect</h3>
<p>When sulfur levels in 316L stainless steel drop below 0.005% by weight, surface tension changes alter how the molten pool behaves. This is the Marangoni effect.</p>
<p>The heat flows outward, failing to penetrate downward. This outward flow increases the outer diameter weld bead width by up to <a href="https://www.swagelok.com/-/media/Distributor-Media/O-S/OKWT/Services/Orbital-Welding-in-Critical-Systems.ashx?la=en&amp;hash=23889DAF6D29F09FD74656B1FBC48E63BFE3F142">50%</a>, according to industry metallurgical guidelines. To force the required penetration depth in low-sulfur heats, you have to increase weld heat input by as much as <a href="https://www.swagelok.com/-/media/Distributor-Media/O-S/OKWT/Services/Orbital-Welding-in-Critical-Systems.ashx?la=en&amp;hash=23889DAF6D29F09FD74656B1FBC48E63BFE3F142">40%</a>. Pushing this much heat into the joint risks degrading the alloy&#8217;s corrosion resistance. It also increases grain growth, which weakens the structural integrity of the final assembly. Matching the sulfur content between the two components to within 0.007% prevents the weld pool from shifting unevenly toward the material with higher sulfur. You must verify the elemental content of your tubing batches rather than trusting manufacturer test reports blindly.</p>
<h2>Phase 2: Dialing in purges and auto-programs</h2>
<p>To move from theoretical metallurgy to shop-floor programming, you must adjust the machine&#8217;s baseline assumptions. Factory-generated weld programs provide a starting point based on tube diameter and wall thickness, but they cannot account for specific material batches or environmental contamination. You have to write manual overrides to match the geometry and chemistry of the joint.</p>
<p>The power supply divides the weld schedule into specific sectors to compensate for gravity as the torch orbits the tube. The puddle behaves differently at the 12 o&#8217;clock position than it does at the 6 o&#8217;clock position.</p>
<ul>
<li>Out-of-the-box factory auto-programs typically require <a href="https://www.weldingweb.com/threads/orbital-tube-welding.23613/">manual amperage adjustments</a> of 5 to 10% to achieve full penetration across varying heats of steel.</li>
<li>Pre-purge times often fail in real-world applications. You frequently need to increase pre-purge from 60 seconds to over <a href="https://app.aws.org/forum/topic_show.pl?tid=35868">three minutes</a> to achieve oxide-free results on sensitive alloys.</li>
<li>Institutional specifications require purging gases to maintain a dew point of -40 degrees Fahrenheit. High-purity applications frequently use 99.9997% pure argon to prevent internal bead discoloration.</li>
<li>Square butt welds on wall thicknesses between <a href="https://www.weldingweb.com/threads/orbital-tube-welding.23613/">0.035 and 0.040 inches</a> tend to crater on top without adding a lip or consumable flange.</li>
<li>Internal gas purge pressure must be fine-tuned to balance the surface tension of the puddle during autogenous butt welds.</li>
</ul>
<p>You cannot rely on the machine to sense these variables automatically. You must interpret the puddle dynamics during test runs and adjust the programming. For example, small diameter tubing under 8mm is susceptible to internal heat tint even with ultra-high purity argon. You must calibrate the internal purge pressure to support the weld bead without blowing it out.</p>
<h2>Phase 3: Scaling to heavy industrial assemblies</h2>
<h3>From benchtop to facility integration</h3>
<p>Scaling isolated orbital welds into large modular builds changes the workflow. You move from programming single tubes to handling entire assemblies. Because orbital welding requires perfect fit-up and zero vibration, handling the surrounding assembly matters just as much as the weld itself.</p>
<p>Controlling the environment prevents drafts from disrupting the shielding gas and maintains the tight temperature controls required for reactive metals like Titanium and Hastelloy. You cannot achieve this level of control on a crowded, unspecialized shop floor. The physical space must accommodate the equipment while isolating the welding zone from external vibrations.</p>
<h3>Executing large-scale thermal equipment</h3>
<p>For example, Harris Thermal engineered and delivered an 11,000,000 BTU/hr hot oil heater integrated with a 2,400 GPM pump for a high-capacity potato pellet line. Applying automated welding to <a href="/shell-and-tube-heat-exchangers/">shell and tube heat exchanger</a> fabrication at this scale ensures the high-pressure joints meet code while keeping the overall assembly timeline intact. Every tube-to-tubesheet joint in a high-capacity heater must withstand continuous thermal cycling. We finalize the weld schedules early in the fabrication process, ensuring repeatable penetration across hundreds of identical joints.</p>
<p>Executing <a href="/products-services/">custom industrial fabrication services</a> at this scale requires specific infrastructure. We operate orbital tube welding equipment with up to a <a href="/capabilities/">2-1/2 inch capacity</a> inside a 50,000-square-foot facility. We also run 100-ton overhead cranes. This lets us position heavy components precisely and build <a href="/food-processing-equipment/">sanitary food processing equipment</a> without relying on subcontractors for material handling. Keeping operations in-house means we control the project timeline. We can rotate a 200,000-pound vessel into the perfect position for an orbital weld without breaking the purge seal.</p>
<p>Scaling up also means managing the purge gas logistics for large volumes. Purging a heat exchanger requires significantly more argon and longer wait times to reach the required dew point than purging a single pipe spool. We design our fabrication sequences to shorten these purge cycles, preventing bottlenecks during final assembly.</p>
<h2>Phase 4: Validating welds and documenting the baseline</h2>
<h3>Understanding non-destructive evaluation limits</h3>
<p>You cannot prove the integrity of an automated weld without matching your inspection method to the material thickness. Standard X-ray non-destructive evaluation under <a href="https://ntrs.nasa.gov/api/citations/20210013409/downloads/OTW-X-ray_NDE_TDT_2021-4-.pdf">NASA-STD-5009</a> cannot resolve the microscopic crack openings in thin-walled orbital tube welds under 0.107 inches thick, creating blind spots in high-pressure systems.</p>
<p>To move past these X-ray limitations on thin-wall tubes, Harris Thermal deploys ASNT Level III certified personnel. These experts apply ultrasonic testing and digital radiography to verify joint integrity. You need this level of inspection to prove that your high-purity lines will hold under operational stress. Relying solely on visual inspection or basic dye penetrant testing leaves your facility vulnerable to pressure failures.</p>
<h3>Offsetting equipment costs through data</h3>
<p>Automated welding equipment costs a lot upfront, but it pays off during quality assurance. Automatically documenting welds directly from the power supply can save up to <a href="https://www.chicago.swagelok.com/resources/learnings/orbital-welding-101">30% of total project construction labor hours</a>. This efficiency is measured against manual data logging, according to component manufacturing benchmarks.</p>
<p>The power supply records the specific amperage, travel speed, and purge time for each weld sector. You can export this data directly into your quality control systems. The recorded data accelerates contractor closeout and simplifies <a href="/repairs/">heat exchanger retubing and repair</a> cycles years down the line. Factoring in these documentation savings provides a more accurate baseline for project estimating. You are not just paying for the weld. You are paying for the verifiable data that proves the weld meets code.</p>
<h2>Delivering predictable fabrication outcomes</h2>
<p>The myth of push-button automation disappears the moment you encounter a mismatched heat of stainless steel or a complex modular assembly. But when you baseline your metallurgical constraints and dial in your purge times, orbital tube welding stops being a source of frustration. The technique becomes a predictable process. Instead of fighting reject rates on the shop floor, you can lock in your parameters and let the machine execute the weld.</p>


<h2>FAQs about orbital tube welding</h2>

<h3>How does orbital GTAW compare to fiber laser welding?</h3>
<p>Fiber laser welding offers higher travel speeds and narrower heat-affected zones than orbital GTAW. However, orbital TIG remains the industry choice for high-purity sanitary lines because it provides control over internal bead profiles and gas purging. Most aerospace and semiconductor specifications still mandate orbital GTAW for pressurized components.</p>

<h3>What is the ROI for switching from manual to orbital welding?</h3>
<p>Automated documentation alone can reduce total project construction labor by [30%](https://www.chicago.swagelok.com/resources/learnings/orbital-welding-101) compared to manual data logging. While equipment costs are higher, the process addresses the shortage of 400,000 skilled manual welders because operators produce repeatable results with less training. Automation typically pays off in high-volume sanitary or aerospace projects.</p>

<h3>Can I use standard orbital heads for Titanium or Duplex?</h3>
<p>Standard orbital heads are compatible with Titanium and Duplex, but they require trailing shields to prevent atmospheric contamination. For reactive metals, you must maintain a shielding gas dew point of -40 degrees Fahrenheit or better to avoid embrittlement. In Harris Thermal, we use custom enclosures to isolate these materials from environmental drafts during the weld cycle.</p>

<h3>How do I prevent cold welds when welding copper tubing?</h3>
<p>Copper&#8217;s high thermal conductivity draws heat away from the joint too quickly for stainless steel weld programs. You must use high-frequency pulsing and higher amperage to maintain a stable molten pool. Pre-heating the assembly or using helium-argon gas mixtures can also help overcome the material&#8217;s heat-sink properties.</p>

<h3>When should I use mandrel bending instead of orbital welding?</h3>
<p>Mandrel bending can reduce labor and material costs by [over 50%](https://www.highpurity.com/orbital-welding/tube/) compared to manual cut-and-weld methods for simple geometries. You should choose bending for continuous runs where space allows for the bend radius. Orbital welding remains necessary for complex modular assemblies or when joining components like valves and flanges that cannot be bent.</p>

