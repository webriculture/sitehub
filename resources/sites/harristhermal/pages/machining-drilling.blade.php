      <div class="px-kicker">Frequently Asked Questions</div>
      <h2>Machining &amp; Drilling FAQs</h2>
    </div>
    <div class="px-faq">
<details><summary>What is CNC tubesheet drilling and why does precision matter?</summary><div class="a"><p>Tubesheets are the drilled plates that hold heat exchanger tubes; each hole must meet tight tolerances for the tube-to-tubesheet joint to seal under pressure and thermal cycling. Harris Thermal drills, reams, and chamfers tubesheets on CNC gantry mills, including a Quickmill with 144&Prime; &times; 240&Prime; travel for very large tubesheets.</p></div></details>
<details><summary>How large a part can you machine?</summary><div class="a"><p>Our boring mills turn up to 16.5 feet (198 inches) in diameter and 60 inches in height &mdash; large enough for tubesheet edges, serrated gasket surfaces, and body flanges on the biggest exchangers we build. CNC drilling and milling centers handle up to 120&Prime; &times; 160&Prime; in a single setup.</p></div></details>
<details><summary>Do you take machining-only jobs, or only machining for your own fabrication?</summary><div class="a"><p>Both. Because we own all the equipment needed to machine every part of a heat exchanger, we offer machining as a standalone service &mdash; CNC tubesheet drilling, plate rolling, press brake forming, burning, waterjet cutting, and large diameter turning.</p></div></details>
<details><summary>Why does in-house machining matter to my project schedule?</summary><div class="a"><p>Every outside vendor in a fabrication chain adds lead time and schedule risk. With machining in-house, Harris Thermal controls nearly every facet of fabrication &mdash; which means faster turnaround, no waiting on subcontractors, and one point of accountability for quality.</p></div></details>
<details><summary>Can you cut baffles to TEMA tolerances?</summary><div class="a"><p>Yes. Our 84&Prime; &times; 168&Prime; waterjet table manufactures baffles to TEMA tolerances, augmenting our CNC baffle drilling capability.</p></div></details>
