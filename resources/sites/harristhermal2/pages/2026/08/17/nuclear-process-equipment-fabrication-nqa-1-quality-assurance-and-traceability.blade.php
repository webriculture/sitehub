    <h1>Nuclear process equipment fabrication: NQA-1 quality assurance and traceability</h1>
    <div class="ht-date">Published August 17, 2026</div>
  </div>
</section>
<div class="ht-postwrap">
  <div class="ht-wrap">
    <article class="ht-article">
      <div class="ht-post-body">
<p>An inquiry package arrives for a shell-and-tube exchanger. The data sheet is unremarkable: 316L, TEMA R, ASME Section VIII, Division 1 — a duty a shop has run a hundred times. Behind it sits a supplier quality requirements attachment running dozens of pages. It invokes a quality assurance standard, hold points, submittals for approval, and a records package due before the unit ships.</p>
<p>The exchanger is ordinary. The obligations attached to it are what separate bidders who can execute from bidders who find out during fabrication.</p>
<p><strong>TL;DR</strong></p>
<ul>
<li>
<p>ASME NQA-1 is a nuclear quality assurance standard. It sets requirements for quality assurance programs, not rules for designing or building equipment.</p>
</li>
<li>
<p>NQA-1 and 10 CFR Part 50, Appendix B govern quality assurance. ASME construction codes govern how equipment is designed and built. Neither substitutes for the other.</p>
</li>
<li>
<p>Heat number traceability is a requirement, not simply a good practice. Appendix B Criterion VIII requires identification "by heat number, part number, serial number, or other appropriate means."</p>
</li>
<li>
<p>Classification determines which controls apply, not the fact that equipment sits at a nuclear facility. RG 1.26, Revision 6 assigns ASME Section VIII, Division 1 to Quality Group D pressure vessels.</p>
</li>
<li>
<p>An ASME Code stamp and an NQA-1 program are different things. Neither implies the other.</p>
</li>
</ul>
<p><strong>On this page:</strong> what NQA-1 is · regulations and codes · which equipment is affected · what changes in the shop · material traceability · common mistakes · FAQs</p>
<h2><strong>What is ASME NQA-1?</strong></h2>
<p>ASME NQA-1, <em>Quality Assurance Requirements for Nuclear Facility Applications</em>, is a nuclear quality assurance standard. It defines what a quality assurance program must contain and control when an organization supplies items or services that perform a safety function at a nuclear facility.</p>
<p>It is not a design code. The standard says nothing about allowable stress, weld joint efficiency, minimum wall thickness, tube sheet thickness, or nozzle reinforcement. Those rules come from the construction code.</p>
<p>What NQA-1 governs is the program around the work: how requirements reach the shop, how conformance is demonstrated and documented, how deviations are captured, and how the evidence stays retrievable years later. ASME’s published scope for the <a href="https://webstore.ansi.org/standards/asme/asmenqa2024">2024 edition</a> covers "the establishment and execution of quality assurance programs during siting, design, construction, operation and decommissioning of nuclear facilities." Facilities in scope include "nuclear power plants (NPP), small modular reactors (SMR), and advanced reactors."</p>
<h3><strong>The 18 Requirements and 10 CFR 50 Appendix B</strong></h3>
<p>NQA-1 is organized into 18 numbered Requirements. They track the 18 criteria of <a href="https://www.ecfr.gov/current/title-10/chapter-I/part-50/appendix-Appendix%20B%20to%20Part%2050">Appendix B to 10 CFR Part 50</a> one for one.</p>
<p>The requirement statements are close enough that fabricators and buyers often treat the two documents as interchangeable in conversation. There are nuances between them that both parties need to understand to establish compliance. Criterion VII, for example, is titled "Control of Purchased Material, Equipment, and Services." The parallel NQA-1 Requirement 7 is "Control of Purchased Items and Services," and the broader term <em>items</em> reaches scope the Appendix B title does not obviously cover.</p>
