<p>Which controls apply to a given order still depends on the equipment’s classification, the governing construction code, and the quality assurance and inspection requirements the owner or EPC invokes. The scope is deliberately specific: balance-of-plant and nuclear-adjacent equipment, fabricated without requiring an ASME Section III Certificate of Authorization. The <a href="/nuclear/">nuclear and DOE fabrication capability</a> page states that boundary directly, including what falls outside it.</p>
