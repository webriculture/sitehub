<p>The regulatory layer sets the terms for everything below it. <a href="https://www.ecfr.gov/current/title-10/chapter-I/part-50/appendix-Appendix%20A%20to%20Part%2050">Appendix A</a>, General Design Criterion 1, requires that structures, systems, and components important to safety "be designed, fabricated, erected, and tested to quality standards commensurate with the importance of the safety functions to be performed." That phrase — <em>commensurate with</em> — is why nuclear quality requirements are graded rather than uniform.</p>
<h3><strong>NRC requirements: Appendix B and Regulatory Guide 1.28</strong></h3>
<p>On NRC-regulated work, NQA-1 is the default quality assurance standard. <a href="https://www.nrc.gov/docs/ML2317/ML23177A002.pdf">Regulatory Guide 1.28, Revision 6</a>, issued September 2023, endorses Parts I and II of NQA-1-2017, NQA-1-2019, and NQA-1-2022 as an acceptable way to meet Appendix B, subject to stated exceptions. That endorsement is what puts NQA-1 into most U.S. commercial nuclear specifications.</p>
<h3><strong>DOE requirements: 10 CFR Part 830</strong></h3>
<p>DOE nuclear facilities operate under a different regulation, and the difference matters when reading a specification. <a href="https://www.ecfr.gov/current/title-10/chapter-III/subchapter-B/part-830/subpart-A/section-830.120">10 CFR Part 830, Subpart A</a> "establishes quality assurance requirements for contractors conducting activities, including providing items or services that affect, or may affect, nuclear safety of DOE nuclear facilities."</p>
<p>Its criteria at <a href="https://www.ecfr.gov/current/title-10/chapter-III/subchapter-B/part-830/subpart-A/section-830.122">10 CFR 830.122</a> are ten performance-based statements rather than Appendix B’s eighteen prescriptive ones. Subpart A does not name NQA-1. DOE contractors invoke it routinely anyway, flowing it down by contract — so on DOE work the applicable standard and edition come from the procurement documents rather than from the regulation.</p>
<h3><strong>Why an ASME Code stamp is not an NQA-1 program</strong></h3>
<p>An ASME Code Certificate of Authorization and the Certification Mark show that a fabricator’s quality control system was accredited for construction under a specific code section. They do not demonstrate an NQA-1 program.</p>
<p>RG 1.28 is explicit about the limit. NRC recognition of the ASME Accreditation Program "applies only to the programmatic aspects of the QA programs," and purchasers "should ensure that the suppliers are effectively implementing their approved QA programs." The reverse also holds: an NQA-1 program confers no Code stamping authority.</p>
<h2><strong>Which nuclear equipment requires these controls?</strong></h2>
<p>Classification determines the applicable controls, not the equipment’s location. A common and expensive assumption is that everything destined for a nuclear site carries nuclear quality requirements. It does not.</p>
<p>Appendix B is scoped to safety function. Its "pertinent requirements … apply to all activities affecting the safety-related functions of those structures, systems, and components," and the program must provide control "to an extent consistent with their importance to safety."</p>
<p><a href="https://www.ecfr.gov/current/title-10/chapter-I/part-50/subpart-A/section-50.2">10 CFR 50.2</a> defines safety-related SSCs as those "relied upon to remain functional during and following design basis events" to assure reactor coolant pressure boundary integrity, safe shutdown, or the capability to prevent or mitigate accident consequences. Equipment outside that definition is not free of quality controls. The controls differ in kind, and are usually reduced in rigor.</p>
