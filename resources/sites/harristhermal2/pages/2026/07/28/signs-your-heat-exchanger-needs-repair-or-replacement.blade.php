<h2>FAQs about signs your heat exchanger needs repair or replacement</h2>

<h3>How does TEMA class affect the repair threshold for a heat exchanger?</h3>
<p>TEMA class determines the corrosion allowance and tube gauge, which sets the structural floor for repairs. A Class R (Refinery) unit typically has thicker walls and more conservative <a href="/2026/05/21/tema-vs-non-tema-heat-exchangers-when-standards-matter/">design margins</a> than Class C (General Service), allowing for more aggressive cleaning or more extensive tube plugging before the pressure boundary is compromised.</p>


<h3>Does NDE tube wall inspection require taking the unit offline?</h3>
<p>Yes, eddy-current and ultrasonic NDE testing require the unit to be drained, opened, and cleaned to allow probe access to the tube internals. While the inspection itself typically takes 1–2 days for a standard bundle, the total downtime includes the cooling and <a href="/harris-thermal-transfer-products-faqs/">cleaning cycle</a> required for accurate sensor readings.</p>


<h3>At what point does tube plugging become a liability?</h3>
<p>Plugging is a short-term fix that becomes a liability once it reduces the total heat transfer area by more than 10–15%. Beyond this point, operators often compensate by <a href="/2026/06/10/how-long-does-a-shell-and-tube-heat-exchanger-last/">increasing process temperatures</a>, which accelerates thermal fatigue and corrosion in the remaining active tubes, leading to a total unit failure.</p>


<h3>When is ASME recertification required after a major repair?</h3>
<p>Recertification with an "R" stamp is required whenever the repair involves work on the pressure-retaining boundary, such as replacing a tubesheet, repairing shell cracks, or adding new nozzles. This process involves <a href="/nuclear/">documented material traceability</a> and inspection by an authorized inspector to ensure the unit still meets ASME Section VIII, Division 1 standards.</p>


<h3>Is fouling-driven U-value loss always reversible with cleaning?</h3>
<p>Fouling is generally reversible through mechanical brushing or chemical circulation if caught early. However, if deposits are left to harden into scale or if the fouling hides under-deposit corrosion, the resulting wall thinning is permanent and cannot be recovered by cleaning, eventually necessitating a retube or replacement.</p>

