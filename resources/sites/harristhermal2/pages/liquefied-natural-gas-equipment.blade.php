<section class="px-block" id="low-temperature">
  <div class="ht-wrap px-split">
    <div class="px-reveal">
      <div class="px-kicker">Low-Temperature Service</div>
      <h2>Shop-fabricated, shipped complete.</h2>
      <p>Harris Thermal fabricates pressure vessels and tanks for low-temperature service in our own shop and ships them complete. Design temperature drives the material, the impact-testing requirement and the weld qualifications, and all three come from the code and the project specification.</p>
      <p>Field erection is outside our scope, so facility-scale field-erected LNG storage tanks are not equipment we supply. See our <a href="/logistics-and-shipping/">shipment planning</a> for how equipment envelope and transportation are worked out early.</p>
