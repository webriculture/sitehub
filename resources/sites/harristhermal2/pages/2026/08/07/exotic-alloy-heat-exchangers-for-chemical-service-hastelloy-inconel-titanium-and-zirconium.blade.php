<h2><strong>Titanium: oxidizing chlorides, and where it stops</strong></h2>
<p>Titanium’s record in chloride cooling water is hard to argue with. ATI reports that millions of feet of welded titanium tubing are in power plant condenser service <a href="https://www.atimaterials.com/Products/Documents/datasheets/titanium/commerciallypure/ati_corrosion_resistant_titanium%20_alloys_tds_en1_v1.pdf">with no reported corrosion failures on the cooling water side</a>, and that its resistance extends across seawater, salt brines, and hot chloride salt solutions.</p>
<p>Grade 2 (R50400) is the commercially pure workhorse for shell-and-tube duty. Grade 7 (R52400) adds 0.12–0.25% palladium for reducing-acid and crevice resistance at roughly five times the price of Grade 2. Grade 12 (R53400) adds small nickel and molybdenum for higher strength and better crevice resistance.</p>
<p>Crevice corrosion sets the service envelope. ATI publishes the commercially pure and palladium-alloyed limits as a temperature ladder, and the Materials Technology Institute adds the Grade 12 figures:</p>
<ul>
<li>
<p>Unalloyed Grades 1–4 typically do not suffer crevice corrosion below <strong>176°F (80°C) at any pH</strong></p>
</li>
<li>
<p>Palladium-alloyed Grades 7, 11, 16, and 17 typically do not suffer crevice corrosion below <strong>480°F (250°C) above pH 1</strong></p>
</li>
<li>
<p>Grade 12 can be used to <strong>464°F (240°C) above pH 2</strong>, and holds to about pH 2 in hydrochloric service against pH 0.1 for Grade 2</p>
</li>
</ul>
<p>Three limits disqualify titanium outright, and all three appear routinely in chemical plants.</p>
<p><strong>Fluoride</strong> attacks titanium by dissolving the protective oxide. The widely repeated 5 ppm limit deserves scrutiny; a fabricator’s technical author states in print that he could not locate its primary source. What is documented is the pH dependence — above roughly pH 3.2 most fluoride exists as free F⁻ rather than undissociated HF, and free fluoride destabilizes the oxide film at tens of ppm. Hot boil-outs are a recognized damage scenario.</p>
<p><strong>Hydrogen absorption</strong> normally occurs, per ATI, when temperature exceeds <strong>176°F (80°C)</strong> and the titanium is galvanically coupled to an active metal or under impressed current, or when <strong>pH falls below 3 or rises above 12</strong>. Galvanic coupling in a mixed-metal exchanger is a metallurgical decision, not a corrosion-allowance question.</p>
<p><strong>Anhydrous chlorine</strong> is the third. ATI lists titanium as incompatible with fluorides, strong reducing acids, very strong caustics, and anhydrous chlorine. Dry chlorine can ignite titanium, and the metal depends on a minimum water content to stay passive. That moisture limit comes from chlorine industry standards rather than the metal supplier, and it must be confirmed against the producer’s specification for any chlorine duty.</p>
<h2><strong>Zirconium: reducing acids, and the oxidizing-ion trap</strong></h2>
<p>Zirconium covers almost exactly the ground titanium cannot. In pure hydrochloric acid it <a href="https://www.atimaterials.com/Products/Documents/datasheets/zirconium/alloy/zircadyne_702_705_in_hydrochloric_acid_v1.pdf">resists attack at all concentrations well above the boiling point</a>, usable above 480°F (250°C) in 10% HCl and to roughly 266°F (130°C) at 37%. In <a href="https://www.atimaterials.com/Products/Documents/datasheets/zirconium/alloy/zircadyne_702_705_in_chloride_solutions_applications_v1.pdf">seawater to 392°F (200°C)</a> ATI reports little or no corrosion with no pitting or crevice attack, noting that zirconium “will not be affected as the titanium is by crevice corrosion” in boiling seawater.</p>
