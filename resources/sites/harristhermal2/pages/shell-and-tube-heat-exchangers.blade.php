      <h2>TEMA shell and tube heat exchangers, fabricated in-house to ASME standards.</h2>
      <p>Harris Thermal is a TEMA shell and tube heat exchanger manufacturer based in Newberg, Oregon, building custom exchangers to TEMA C, B, and R classes and ASME Section VIII since 1885 — in materials from carbon steel to titanium and zirconium. Shell and tube heat exchangers are the workhorses for heating and cooling large volumes of process fluids and gases. They deliver reliable heat transfer performance through high turbulence and counter flow across one or more passes — and Harris Thermal can supply turbulators to enhance efficiency further.</p>
      <p>With over 140 years of experience — and because we produce all parts necessary for heat exchanger fabrication in-house — we can meet demanding design and quality criteria. Our engineering team partners with you to design and optimize a heat exchanger built for your exact process, timeline, and budget.</p>
