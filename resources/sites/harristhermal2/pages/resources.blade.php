<section class="px-block">
  <div class="ht-wrap">
    <div class="px-sec-head px-reveal"><div class="px-kicker">Understanding TEMA</div><h2>What TEMA standards mean for your equipment.</h2><p>TEMA — the Tubular Exchanger Manufacturers Association — is a set of standards developed by leading shell and tube manufacturers, defining exchanger styles plus machining and assembly tolerances. Selecting a TEMA-compliant manufacturer assures you the equipment you install is built to defined specifications and criteria.</p></div>
    <div class="px-fig px-reveal">
      <img src="/sites/harristhermal2/wp-content/uploads/2022/06/fig7.png" alt="Common shell and tube heat exchanger configurations (TEMA, 1999)">
      <p style="color:var(--ht-muted);font-size:.85rem;margin:10px 0 0;text-align:center">Figure 7.1 (TEMA, 1999) — commonly used heat exchanger configurations</p>
    </div>
    <div class="px-whys"><div class="px-why px-reveal"><h4>TEMA C — General Service</h4><p>The least restrictive and most widely used classification.</p></div><div class="px-why px-reveal"><h4>TEMA B — Chemical Service</h4><p>Adds requirements like confined gasket joints, spiral wound gaskets, and greater minimum thicknesses.</p></div><div class="px-why px-reveal"><h4>TEMA R — Refinery Service</h4><p>Similar to B — the most stringent requirements for severe refinery duty.</p></div></div>
    <div class="px-sec-head px-reveal" style="margin:44px auto 0">
      <p>TEMA designations describe the complete exchanger: in a <strong>TEMA Type BEM</strong>, the &ldquo;B&rdquo; is the front head, &ldquo;E&rdquo; the shell, and &ldquo;M&rdquo; the rear head design. Want to go deeper? Read our <a href="/2026/05/13/what-is-a-tema-heat-exchanger/">TEMA heat exchanger guide</a> and <a href="/2026/05/19/understanding-tema-classes-r-c-and-b/">TEMA classes explainer</a>, or browse all our <a href="/category/industry-insights/">Industry Insights</a>.</p>
    </div>
  </div>
</section>
