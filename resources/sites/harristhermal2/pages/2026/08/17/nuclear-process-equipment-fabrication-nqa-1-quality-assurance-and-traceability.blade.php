<p>The pattern is consistent across every row. Nuclear fabrication is distinguished less by better welding than by the requirement to demonstrate and document each step: performed to an approved requirement, by qualified people, using calibrated equipment, with every deviation captured and dispositioned.</p>
<p>Appendix B Criterion IX puts it in its own terms. Special processes, "including welding, heat treating, and nondestructive testing, are controlled and accomplished by qualified personnel using qualified procedures." Every verb in that clause concerns control rather than skill.</p>
<h2><strong>Material traceability in nuclear fabrication</strong></h2>
<p>Traceability is a requirement, not a matter of good housekeeping, and it is where these controls become concrete on the shop floor.</p>
<p>Appendix B Criterion VIII requires measures for "the identification and control of materials, parts, and components, including partially fabricated assemblies." Those measures must "prevent the use of incorrect or defective material, parts, and components." Identification is maintained "by heat number, part number, serial number, or other appropriate means, either on the item or on records traceable to the item."</p>
<p>Criterion VII adds the delivery-side obligation. Documentary evidence of conformance "shall be available at the nuclear power plant or fuel reprocessing plant site prior to installation or use of such material and equipment." A records package is therefore a contractual deliverable, not paperwork assembled at the end.</p>
<h3><strong>How traceability survives fabrication</strong></h3>
<p>Traceability is a chain, and it has to hold at every transfer. Follow a single plate heat entering the shop for a vessel shell:</p>
<ol>
<li>
<p><strong>Certification.</strong> The mill issues a Certified Material Test Report (CMTR) identifying the specification and grade, heat number, chemical analysis, and mechanical test results.</p>
</li>
<li>
<p><strong>Receiving inspection.</strong> A written procedure verifies the CMTR against the purchase order, and the marking on the plate against the CMTR. Material is released to production only after acceptance.</p>
</li>
<li>
<p><strong>Identification transfer.</strong> When the plate is cut, the heat number carries to every piece — by stamping where the specification permits it, by a marking method suited to thin or corrosion-sensitive material where it does not, and by a documented transfer record wherever forming or machining will remove the mark.</p>
</li>
<li>
<p><strong>Traceability through fabrication.</strong> As the piece is formed, fitted, and welded, the traveler ties that heat to the weld records, the filler metal heat or lot, the examination reports, and any heat treatment.</p>
</li>
<li>
<p><strong>Final documentation.</strong> The completed package maps each heat to its location in the finished equipment. A reviewer can start from any weld or component and trace back to the mill certification.</p>
</li>
</ol>
<p>Step 3 is a critical point in the traceability chain. Cutting, forming, and machining can remove markings, so the documented transfer matters as much as the original identification.</p>
<h3><strong>What positive material identification does and does not do</strong></h3>
<p>PMI verifies that the metal in the shop matches what the paperwork says. It is the practical defense against mixed alloys in a shop running many grades. It does not replace a CMTR; it confirms the CMTR belongs to the material on the floor.</p>
<p>One documented case shows why verification is needed alongside certification. <a href="https://www.nrc.gov/docs/ML0936/ML093620098.pdf">NRC Information Notice 2008-04</a> reported counterfeit stop check valves carrying a recognized manufacturer’s name supplied to a nuclear plant. One was installed on a stator cooling water pump discharge in a non-safety-related system, where it ran eight months before discovery. A second sat in warehouse inventory.</p>
<p>Documentation accompanied those parts the entire time. Paperwork alone could not have caught them.</p>
<h2><strong>Common mistakes in nuclear equipment procurement</strong></h2>
<ul>
<li>
<p><strong>Assuming a nuclear site imposes nuclear quality requirements on everything.</strong> Appendix B is scoped to activities affecting safety-related functions, and RG 1.26 assigns Section VIII, Division 1 to Quality Group D vessels. Classification comes first.</p>
</li>
<li>
<p><strong>Treating an ASME Code stamp as evidence of an NQA-1 program.</strong> NRC recognition of ASME accreditation reaches only the programmatic aspects of Code work, and leaves implementation verification with the purchaser.</p>
</li>
<li>
<p><strong>Describing equipment as "NQA-1 certified."</strong> NQA-1 applies to programs. Equipment is built to a construction code, under a quality assurance program.</p>
</li>
<li>
<p><strong>Leaving classification and quality assurance scope out of the inquiry.</strong> A bidder who is not told which Requirements apply, which hold points exist, and what records are due will price a different job than the one being bought.</p>
</li>
<li>
<p><strong>Discovering documentation requirements after fabrication starts.</strong> Traceability that was not recorded at cutting cannot be reconstructed at final inspection. The affected material usually has to be scrapped or re-certified.</p>
</li>
<li>
<p><strong>Applying NQA-1 uniformly to avoid making a classification decision.</strong> Blanket application raises cost without adding safety margin, and it buries the requirements that actually matter.</p>
</li>
</ul>
<h2><strong>Define the scope before the inquiry goes out</strong></h2>
<p>Successful nuclear equipment procurement depends less on specification length than on five decisions being stated clearly:</p>
<ol>
<li>
<p>The equipment’s safety classification, and the basis for it.</p>
</li>
<li>
<p>The applicable design and construction code and edition.</p>
</li>
<li>
<p>The applicable quality assurance requirements, including the standard, edition, and which Requirements apply.</p>
</li>
<li>
<p>The inspection requirements, including witness and hold points and notification lead times.</p>
</li>
<li>
<p>The documentation and records requirements, including retention and format.</p>
</li>
</ol>
<p>Those five answers turn an ambiguous inquiry into a biddable scope. They also distinguish the fabricators who understand the obligations from those who have read only the data sheet.</p>
