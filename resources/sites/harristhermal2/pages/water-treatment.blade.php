<section class="px-block soft" id="zld">
  <div class="ht-wrap px-split">
    <div class="px-reveal">
      <div class="px-kicker">Zero Liquid Discharge</div>
      <h2>Equipment for the end of the recovery train.</h2>
      <p>A ZLD train is a sequence, not a single machine: pre-concentration, thermal evaporation, then crystallization to solids. Each stage hands a harder stream to the next, and the metallurgy usually has to change with it.</p>
      <p>Harris Thermal fabricates the evaporators, crystallizers, condensers, exchangers and vessels those stages need, in materials matched to where in the train the equipment sits.</p>
      <ul class="px-checks">
        <li>Falling-film and forced-circulation evaporators</li>
        <li>Crystallizers for final solids recovery</li>
        <li>Condensers and heat recovery exchangers</li>
        <li>High-alloy and clad construction</li>
      </ul>
