      <div class="px-kicker">FAQs</div>
      <h2>General manufacturing equipment questions.</h2>
    </div>
    <div class="px-faq">
<details><summary>What equipment does Harris Thermal fabricate for general industrial applications?</summary><div class="a"><p>Shell-and-tube heat exchangers, condensers, reboilers, process heaters and coolers, replacement exchangers and tube bundles, ASME Section VIII pressure vessels, process and mixing vessels, storage and custom tanks, evaporators, crystallizers, columns, scrubbers, cyclones, and other custom process equipment. Harris Thermal fabricates equipment for integration into your process; pumps, instrumentation and controls are not part of our standard supply scope.</p></div></details>
<details><summary>Can Harris Thermal build a one-off or replacement piece of equipment?</summary><div class="a"><p>Yes. A single custom vessel or exchanger is normal work here, not an exception. Replacement equipment can be built to existing envelope and nozzle geometry so it drops into the piping and supports already there, re-tubed where the shell is sound, or re-rated for a duty above the original basis. Existing drawings, field measurements or a reverse-engineered specification are all workable starting points.</p></div></details>
<details><summary>What materials and construction methods are available?</summary><div class="a"><p>Carbon steel, stainless steels, duplex stainless, AL-6XN, Hastelloy, Inconel, Monel, titanium and other qualified specialty materials, plus clad and explosion-bonded construction where a corrosion-resistant wetted surface over a structural carbon-steel backing suits the design. Large-diameter and heavy-wall work is handled in-house.</p></div></details>
