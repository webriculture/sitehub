<details><summary>What equipment does Harris Thermal fabricate for chemical processing?</summary><div class="a"><p>Tubular and fixed-bed reactors, fluid-bed reactors, jacketed reactors, ASME Section VIII pressure vessels, process and mixing vessels, fractionation and distillation columns, reboilers, overhead condensers, shell-and-tube heat exchangers, replacement exchangers and tube bundles, falling-film and forced-circulation evaporators, scrubbers, cyclones, adsorber vessels, and storage and process tanks. Harris Thermal fabricates equipment for integration into your process; it does not supply the process design or the complete plant.</p></div></details>
