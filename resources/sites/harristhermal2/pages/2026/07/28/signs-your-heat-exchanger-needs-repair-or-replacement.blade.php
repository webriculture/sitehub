    <h1>Signs your heat exchanger needs repair or replacement</h1>
    <div class="ht-date">Published July 28, 2026</div>
  </div>
</section>
<div class="ht-postwrap">
  <div class="ht-wrap">
    <article class="ht-article">
      <div class="ht-post-body">
<p>Fouling strips 10–30% of thermal efficiency before any standard process alarm fires. By the time energy cost overruns show up in a refinery’s operating budget, the damage is already weeks or months old. The unit did not fail suddenly. It failed gradually, in plain sight, while the numbers that reveal it went unread. This article covers the quantitative indicators that appear early, along with the decision criteria for choosing between repair, retubing, and full replacement.</p>
<p><strong>TL;DR</strong></p>
<ul>
<li>A U-value decline of 15–25% from baseline means schedule an inspection now.</li>
<li>Delta-P rising independent of flow changes signals fouling at design-allowance levels.</li>
<li>Widespread tube failure typically means replacement, not repair.</li>
<li>When repair costs reach 60–70% of a new unit’s price, replacement is the better choice.</li>
<li>NDE tube wall inspection every 18–24 months produces the data that drives this call.</li>
</ul>
<h2>The warning signs: lost performance, rising pressure drop, and leaks</h2>
<p>Process dashboards show temperature and flow. They rarely trend the two numbers that reveal heat exchanger degradation earliest.</p>
<h3>U-value decline</h3>
<p>The overall heat transfer coefficient (U-value) is the most direct measure of exchanger performance. In shell-and-tube units handling hydrocarbon service, a U-value decline of 15–25% from the post-commissioning baseline signals fouling heavy enough to schedule an inspection. Plate exchangers hit that threshold sooner because their tighter channel gaps foul faster.</p>
<p>A single low reading is noise. A consistent downward trend over successive run cycles is a signal. Log U-value at regular intervals from day one to ensure a baseline exists for trend analysis.</p>
<h3>Delta-P rise</h3>
<p>Pressure drop across the tube side, measured independently of any flow rate changes, is the second leading indicator. In crude preheat trains, a 20–30% rise in tube-side Delta-P over a run cycle often means fouling resistance has reached the TEMA design allowance. When Delta-P climbs while flow stays constant, something is restricting the tubes.</p>
<h3>External leaks</h3>
<p>Visible leaks at nozzle joints, tube sheet faces, or gasket lines are late-stage indicators by comparison, but they still arrive before a total pressure boundary failure. A seeping flange may indicate a failed weld or a pressure boundary compromised by corrosion. Treat any external leak as grounds for immediate inspection scheduling. Do not patch and continue.</p>
<p>Monitoring inlet and outlet temperatures alongside pressure drops gives operators the early signs of performance loss before any single metric crosses an alarm threshold.</p>
<h2>The mechanisms of degradation: fouling, scaling, corrosion, and tube failure</h2>
<p>The performance numbers tell you something is wrong. Understanding the mechanism tells you how serious it is.</p>
<h3>Fouling and scaling</h3>
<p>Fouling deposits act as insulators on tube walls. They reduce heat transfer without structurally damaging the metal, which means the damage is recoverable. Chemical cleaning or mechanical brushing can restore much of the lost U-value if caught before the deposits harden into scale. Scale is harder to remove and may require more aggressive intervention.</p>
<h3>Corrosion and wall thinning</h3>
<p>Corrosion is a different category of problem entirely. Pitting, thinning, and discoloration on tubes or shells indicate irreversible material loss. Cleaning cannot recover it. Once wall thickness drops below minimum code allowances, the tube is a structural liability. A unit’s resistance to corrosion is determined at specification: alloy selection, tube gauge, and TEMA class. Those choices set the <a href="/2026/06/10/how-long-does-a-shell-and-tube-heat-exchanger-last/">lifespan ceiling</a> the unit will never exceed, regardless of how well it is maintained after delivery.</p>
<h3>Thermal fatigue and tube-to-tubesheet failure</h3>
<p>Repeated thermal cycling introduces micro-cracking at tube-to-tubesheet joints, often the first structural failure mode in high-cycle service. Flow-induced vibration compounds this, producing a broadband frequency signature that corresponds to tube bundle loosening. Acoustic emission monitoring can detect early micro-cracking at tube-to-tubesheet joints before any visible leak develops, which is why it belongs in any formal inspection protocol.</p>
<p>One scope boundary worth naming: the criteria above apply to industrial shell-and-tube units, where the repair/replace call is a cost-and-performance calculation. Gas-fired residential furnace heat exchangers follow a different rule. Any confirmed crack in that application is a condemn event: combustion gases share air with occupied space, and there is no repair threshold to calculate. The numeric criteria in this article do not transfer to that context.</p>
<h2>Repair or replace? How to make the call</h2>
<p>The repair-or-replace decision hinges on three variables: tube failure rate, shell integrity, and the cost ratio relative to a new unit. Most operators reach it after the performance trends are already moving.</p>
<h3>When repair is viable</h3>
<p>Repair makes sense when tube leaks are isolated, the shell remains structurally sound, and cleaning can recover the lost U-value. A small number of failed tubes can be plugged or replaced without compromising the unit’s pressure boundary or its certification status. Targeted repair in this scenario costs a fraction of replacement and extends service life through the next planned turnaround.</p>
<h3>When replacement is the right call</h3>
<p>Replacement becomes the correct decision when tube failure is widespread. The threshold: when more than 20–25% of tubes have failed, replacement <a href="/harris-thermal-transfer-products-faqs/">is typically the better choice</a>. Below that level, targeted repair or retubing remains viable. Above it, the remaining tubes carry elevated stress, heat transfer area is compromised, and continued patching delays the inevitable.</p>
<p>Two additional triggers override the tube-count rule:</p>
<ul>
<li>Corrosion that threatens the pressure boundary, including shell integrity or nozzle condition</li>
<li>Repair costs that approach 60–70% of the price of a new unit</li>
</ul>
<p>When repair cost hits that ratio, the economics of replacement are almost always better. Carrying a degraded unit through another cycle accumulates repair spend on equipment that still needs replacing. That threshold is <a href="/2026/05/21/tema-vs-non-tema-heat-exchangers-when-standards-matter/">consistent with broader industry practice</a> for aging pressure equipment.</p>
<h3>The lead-time problem</h3>
<p>The cost comparison above does not account for the schedule risk of getting this decision wrong. Repair lead times of 6–20 weeks are common when the unit requires ASME U-stamp or PED recertification after major work. A unit that looked like a repair candidate becomes a capital and scheduling crisis the moment recertification is required and no spare exists. Both paths carry real cost. The financial case for catching this decision early, while scheduling options still exist, is plain.</p>
<h2>When retubing is the smarter, cheaper fix</h2>
<p>Most guides present repair and replacement as the only options. Retubing is often the better path when the failure falls between those extremes.</p>
<p>When fewer than 20% of tubes have failed and the shell is structurally sound, <a href="/2026/06/10/how-long-does-a-shell-and-tube-heat-exchanger-last/">retubing preserves the pressure vessel investment</a>. You keep the shell, the nozzles, and the tubesheet. You replace the tube bundle. The result is a new heat transfer surface inside a verified pressure boundary, at a fraction of full replacement cost.</p>
<p>Retubing does not make sense when shell corrosion is driving the degradation, or when the unit is already near its TEMA class service life ceiling. In those cases, a new tube bundle inside a compromised shell shifts the failure mode without resolving it.</p>
<h2>Why a Test &amp; Evaluate (NDE) inspection beats guessing</h2>
<p>Performance curves tell you that something has changed. NDE tells you what changed and whether the metal can still be trusted.</p>
<p>Tube wall inspection using ultrasonic or eddy-current NDE measures remaining wall thickness at multiple points along each tube. Wall thickness measurements at each tube drive the repair, retube, or replace decision with hard numbers instead of estimates. Acoustic emission monitoring adds a second layer by detecting joint micro-cracking at tube-to-tubesheet connections before any wall thinning shows up in a thickness scan.</p>
<p>An NDE interval of 18–24 months is the standard for most industrial service conditions. In aggressive chemical or high-cycle thermal service, that interval may warrant shortening. Without current wall thickness data, every repair or replacement decision carries uncertainty that the capital cost does not justify.</p>
<h2>Catching problems early with a regular inspection schedule</h2>
<p>The goal is a plant-floor habit, not a periodic audit. Trending produces the early warning that single-point readings miss.</p>
<ul>
<li>Log inlet and outlet temperatures and tube-side Delta-P at consistent intervals throughout each run cycle. The trend line matters more than any individual reading.</li>
<li>Calculate U-value from logged temperatures at the same intervals. A sustained downward slope, not a single dip, is the trigger for scheduling a formal inspection.</li>
<li>Schedule mechanical brushing or chemical cleaning based on Delta-P trend, not calendar date. Cleaning driven by data costs less than cleaning driven by guesswork.</li>
<li>Watch for compensating behavior on the process side. Running higher temperatures to offset fouling-driven heat loss <a href="/2026/06/10/how-long-does-a-shell-and-tube-heat-exchanger-last/">accelerates degradation</a> and masks how far performance has already slipped.</li>
<li>Trigger a formal NDE evaluation when U-value decline reaches 10–15% for plate exchangers or 15% for shell-and-tube units. Getting there before the 25% threshold means the decision is still on your schedule, not the unit’s.</li>
</ul>
<h2>Getting to the repair or replace call before it becomes an emergency</h2>
<p>Operators who arrive at the repair/replace decision with trending data and current NDE wall measurements have options. Operators who arrive at it after a process upset or a failed alarm response face a 6–20 week recertification clock. They work with whatever spare capacity the plant can scramble.</p>
<p>The three numbers that matter: a 15–25% U-value decline, more than 20–25% tube failure, and a repair cost at 60–70% of a new unit. Read those before the alarm fires and the decision stays on your schedule.</p>
