<h2><strong>Cost, thickness, and construction</strong></h2>
<p><strong>Allowable stress often beats price per pound.</strong> Ti Grade 12 carries an ASME Section VIII Division 1 allowable of 20,000 psi at 100°F, declining to 12,300 psi at 600°F. Zr 702 runs 15.7 ksi from -20 to 100°F, falling to 5.2 ksi at 700°F, while Zr 705 runs 22.9 ksi to 11.3 ksi over the same range. Those values set wall thickness, and thickness sets cost. The Materials Technology Institute published a case in which Grade 12 at $15.07/lb against Grade 2 at $13.34/lb — a 15% premium per pound — produced a vessel costing <strong>21% less in material</strong>, because the higher allowable permitted thinner sections. Comparing alloys on price per pound inverts that result. Titanium in appropriate service is also commonly specified with no corrosion allowance, which removes sacrificial metal from the wall, though that is a design convention to be agreed with the fabricator rather than a code entitlement.</p>
<p><strong>Thermal conductivity is less of a penalty than engineers expect.</strong> ATI publishes Zr 702 at 22 W/m·K and describes zirconium’s conductivity as more than 30% higher than that of stainless steel alloys. Commercially pure titanium sits in the same general band as austenitic stainless rather than well below it. The meaningful gap is against carbon steel, near 54 W/m·K, and in fouling-limited or film-limited service that difference is usually secondary to the controlling film coefficients. Where a design is genuinely conduction-limited, the tube wall calculation should be run on the actual grade’s published conductivity rather than on a family assumption.</p>
<p><strong>Clad construction limits exotic alloy to the wetted surface.</strong> Clad plate in these metals is covered by <a href="https://store.astm.org/b0898-11r16.html">ASTM B898</a> for titanium, zirconium, tantalum, and niobium, and by ASTM A263, A264, and A265 for stainless and nickel cladding, the latter two requiring shear and bond strength testing. One published fabricator guideline puts the crossover where a solid design would need cladder thickness above roughly <strong>0.625 in. for reactive metals and high-nickel alloys</strong>, or about <strong>1 in. for austenitic and duplex stainless</strong>. A second constraint belongs in the specification. In weld-repair development work on titanium-clad carbon steel, positive material identification showed contamination becoming problematic once remaining clad thickness fell below <strong>0.048 in.</strong>, and the study concluded that welding on clad thinner than <strong>0.078 in.</strong> is highly risky. Specify clad thickness with future repair in mind, not only initial corrosion allowance.</p>
<h2><strong>Fabrication and inspection controls that decide service life</strong></h2>
<p>For reactive metals, fabrication practice is part of the metallurgy rather than an overlay on it.</p>
<p><strong>Iron is an interstitial contaminant, not shop dirt.</strong> <a href="https://pubs.aws.org/p/2066/g24g24m2021-guide-for-the-fusion-welding-of-titanium-and-titanium-alloys">AWS G2.4/G2.4M:2021</a>, the guide for fusion welding titanium, contains a clause titled “Oxygen, Nitrogen, Carbon, and Iron in Titanium,” grouping iron with the interstitials that embrittle the metal. <a href="https://store.astm.org/b0614-26.html">ASTM B614</a> states that cleaned zirconium should show “no evidence of paint, oil, grease, glass, graphite, lubricant, scale, abrasive, iron, or other forms of contamination,” and <a href="https://store.astm.org/b0600-22.html">ASTM B600</a> covers the equivalent for titanium. Both are a practice and a guide rather than mandatory specifications, so they take effect when the purchase documents invoke them. IMOA is blunt about the consequence for stainless: fabricating stainless and carbon steel in the same shop is particularly prone to iron contamination from carbon steel grinding dust. Dedicated tooling, stainless-only brushes, segregated storage, and pickling are the controls.</p>
<p><strong>Shielding requirements differ categorically from stainless work.</strong> AWS G2.4 specifies shielding gas purity <em>and</em> dew point, and documents trailing shields, backup shields, and argon-purged chambers as standard practice. The process coverage itself is telling: G2.4 addresses GTAW, GMAW, PAW, and laser welding for titanium, while <a href="https://pubs.aws.org/p/2271/g25g25m2025-guide-for-the-fusion-welding-of-zirconium-and-zirconium-alloys">AWS G2.5/G2.5M:2025</a> addresses only GTAW and PAW for zirconium. On austenitic and duplex stainless, a nitrogen backing purge is accepted practice and small carbon dioxide additions stabilize the GMAW arc. Neither gas belongs near titanium or zirconium.</p>
<p><strong>Weld color is a controlled acceptance criterion.</strong> Both AWS G2.4 and G2.5 include a table and figure covering weld surface color, running from bright silver through straw and blue to gray and white flaky powder as contamination increases. The accept/reject boundary is set by the governing code or purchase specification, so it belongs in the inquiry documents rather than on the shop floor. One code detail is often missed: AWS D1.9, the structural welding code for titanium, specifically excludes titanium pressure vessels and fluid-carrying pipe lines from its scope.</p>
<p><strong>Qualification and post-weld treatment.</strong> Welding procedures are qualified by base metal grouping under ASME Section IX Table QW/QB-422, and titanium and zirconium each occupy their own P-number ranges separate from the stainless and nickel groups. Confirm the applicable group against the current table when writing the specification, because it determines which qualifications a shop must already hold. ATI specifies a stress relief for zirconium at 1050°F ±50°F for half an hour to an hour, and states that Zr 705 requires stress relief <strong>within 14 days after welding</strong>. Haynes recommends re-annealing C-276 once outer fiber elongation exceeds about 7%, because cold work can affect stress corrosion cracking resistance.</p>
<p><strong>Inspection methods and their limits.</strong> Eddy current testing is the applicable tube examination, and <a href="https://store.astm.org/e0426-16r21.html">ASTM E426</a> covers titanium, stainless, and similar low-conductivity alloys including nickel alloys — low electrical conductivity is the shared challenge the standard is written around. <a href="https://store.astm.org/b0338-17r21.html">ASTM B338</a>, the titanium condenser and heat exchanger tube specification, builds electromagnetic, ultrasonic, hydrostatic, and pneumatic testing in rather than leaving them to the purchaser. Where cross-stream leakage is unacceptable, helium mass spectrometer leak detection detects leakage down to 1 × 10⁻⁸ Pa·m³/s under <a href="https://store.astm.org/e0498_e0498m-11r22.html">ASTM E498</a>, and a vented double tubesheet makes any tube-joint leak externally detectable. Penetrants used on titanium and stainless must be controlled for halogen and sulfur content.</p>
<p><strong>One hazard specific to zirconium.</strong> At intermediate corrosion rates, zirconium grains can become trapped in the surface oxide, creating a pyrophoric fire hazard. ATI advises steam or hot-air treatment before the equipment is exposed to air. That is a turnaround procedure, and it rarely appears in operating manuals written around stainless equipment.</p>
<h2><strong>Common mistakes in exotic alloy specification</strong></h2>
<ul>
<li>
<p><strong>Ranking alloys instead of matching mechanisms.</strong> There is no “better” between titanium and zirconium; one handles oxidizing chlorides and fails in reducing acid, the other reverses it.</p>
</li>
<li>
<p><strong>Leaving trace contaminants out of the design basis.</strong> Ferric and cupric ions disqualify both Hastelloy B-3 and zirconium; fluoride disqualifies titanium and zirconium. These species are often absent from the data sheet and present in the stream.</p>
</li>
<li>
<p><strong>Specifying nominal concentration without upset conditions.</strong> Zirconium’s sulfuric acid resistance breaks between 77% and 77.5%, so a unit designed at 75% has roughly two percentage points of excursion margin.</p>
</li>
<li>
<p><strong>Treating a low chloride analysis as clearance for 316L.</strong> Concentration under deposits, at wet/dry interfaces, and beneath insulation causes cracking well below the bulk threshold.</p>
</li>
<li>
<p><strong>Comparing alloys on price per pound.</strong> Allowable stress determines thickness, and thickness determines cost.</p>
</li>
<li>
<p><strong>Assuming a shop that welds stainless can weld titanium.</strong> Segregation, shielding, purity control, and weld color acceptance form a separate discipline with its own AWS guides.</p>
</li>
</ul>
<h2><strong>Specify the environment, not the alloy</strong></h2>
<p>The most useful thing an engineer brings to an exotic alloy inquiry is not a material preference. It is a complete environmental description: full ionic composition including trace oxidizing species and fluoride, pH range across startup and upset, maximum skin temperature rather than bulk temperature, and an honest account of stagnant volumes and shutdown conditions. Every alloy here has a documented environment that destroys it, and in most failures the destroying species was present in the process and absent from the data sheet.</p>
<p>Harris Thermal fabricates <a href="/shell-and-tube-heat-exchangers/">shell-and-tube heat exchangers</a> and <a href="/pressure-vessels-tanks/">ASME Section VIII pressure vessels</a> in high-alloy construction, with <a href="/engineering/">in-house thermal and mechanical design</a> and <a href="/fabrication/">fabrication, examination, and hydrostatic testing under one roof</a>. Where a bundle needs replacement and the original drawings are gone, positive material identification and reverse engineering establish grade and geometry before material is ordered. The <a href="/2026/05/13/what-is-a-tema-heat-exchanger/">TEMA classifications guide</a> covers what each class controls in a fabricated unit, and the <a href="/chemical-industry-equipment/">chemical processing equipment page</a> covers separation and reaction service applications.</p>
<h2><strong>FAQs about exotic alloy heat exchangers</strong></h2>
<h3><strong>When should a specification move from 316L to a duplex or 6% molybdenum grade?</strong></h3>
<p>When chloride can concentrate at the metal surface, or when temperature approaches 122°F (50°C) in chloride service. Type 316L has an ASTM G48 critical pitting temperature near 50°F (10°C), and near boiling it can crack at under 1 ppm chloride. The 6% molybdenum superaustenitics carry PREN values of 41–45 against 24–26 for 316L.</p>
<h3><strong>What is the practical difference between Hastelloy C-276 and C-22?</strong></h3>
<p>C-276 runs 16% chromium against 16% molybdenum; C-22 runs 22% chromium against 13% molybdenum. Higher chromium improves oxidizing-acid performance, higher molybdenum favors reducing acids. Haynes publishes elevated C-22 rates in 70–90% sulfuric at and above 150°F. For C-276 in nitric acid, the published rate is 2.62 mm/y at 70% and 200°F (93°C), rising to 18.42 mm/y in 60% acid at boiling. Temperature dominates concentration in that service.</p>
<h3><strong>Can titanium be used in hydrochloric or sulfuric acid service?</strong></h3>
<p>Not as a general solution — ATI lists titanium as incompatible with strong reducing acids. Grade 12 extends usable range to about pH 2 in hydrochloric service against pH 0.1 for Grade 2, but zirconium is the alloy selected for hydrochloric duty at meaningful concentration and temperature, provided the stream carries no oxidizing ions.</p>
<h3><strong>Why does ferric ion contamination matter so much for zirconium?</strong></h3>
<p>Zirconium’s passive film is stable in reducing conditions and breaks down under oxidizing attack. As little as 50 ppm of ferric ion triggers pitting in 10% hydrochloric acid at 212°F (100°C), and at 500 ppm ferric, stress corrosion cracking occurs at every temperature tested. Upstream equipment corrosion is a common source, so the design basis should reflect achievable stream purity. The same restriction applies to Hastelloy B-3.</p>
<h3><strong>What is the upper temperature limit for duplex stainless in a pressure vessel?</strong></h3>
<p>IMOA tabulates the maximum ASME design temperature for 2205 and 2507 at 600°F (315°C), with European TüV practice at 480°F (250°C). The limit exists because alpha prime forms in the ferrite phase, which IMOA places between 575°F and 980°F (300–525°C). That is separate from sigma phase, which forms roughly between 1300°F and 1830°F (700–1000°C) and is a welding and annealing concern rather than a service one. Confirm the governing figure against ASME Section II Part D for the specific product form.</p>
<h3><strong>When is clad construction preferable to solid exotic alloy?</strong></h3>
<p>One published fabricator guideline puts the crossover where a solid design would need cladder thickness above roughly 0.625 in. for reactive metals and high-nickel alloys, or about 1 in. for austenitic and duplex stainless — a rule of thumb rather than a code rule, and worth pricing both ways on a specific job. Clad plate for titanium and zirconium falls under ASTM B898; nickel and stainless clad under ASTM A265 and A264. Specify thickness with future weld repair in mind, since development work on titanium-clad carbon steel found repair welding highly risky below about 0.078 in. remaining clad thickness.</p>
<h3><strong>What should a fabricator be asked before an exotic alloy exchanger is awarded?</strong></h3>
<p>Whether reactive-metal work runs in a segregated area with dedicated tooling; how shielding gas purity and dew point are controlled and verified; which weld color acceptance criteria apply and to what standard; how procedures are qualified under ASME Section IX for the applicable P-number group; and how post-weld thermal treatment is handled for zirconium. AWS G2.4 and G2.5 govern titanium and zirconium fabrication, and neither overlaps ordinary stainless practice.</p>

