<td align="left">Shoulder and winter hours</td>
<td align="left">Tower water</td>
<td align="left">Needs an exchanger and a supply temperature it can satisfy</td>
</tr>
</tbody>
</table>
<p>One distinction controls the whole table. An open cooling tower approaches the ambient <strong>wet bulb</strong>; a dry cooler approaches the <strong>dry bulb</strong>. That sets the achievable facility water temperature on a design day, and therefore the temperature available to the CDU.</p>
<p>SPX’s <a href="https://spxcooling.com/wp-content/uploads/Cooling-Tower-Fundamentals.pdf"><em>Cooling Tower Fundamentals</em></a> defines approach as the difference between cold water temperature and entering wet bulb. It adds a piece of commercial reality: “it is not customary in the cooling tower industry to guarantee any approach of less than 5°F.”</p>
<p>Warm-water operation buys free cooling hours, and the payoff is climate-specific. Uptime Institute reports systems running on free cooling “50% to 80% or more of the time.” A 2025 Cooling Technology Institute paper reports <a href="https://spxcooling.com/wp-content/uploads/TP25-25-Managing-Water-of-Adiabatic-Systems-CTI-Paper-Final-Draft-1172025-1.pdf">water reduction “up to 90%”</a> for an adiabatic cooler against an evaporative tower, while naming scale growth on the pre-cooling media as the failure mode to design against.</p>
<h3><strong>Why warmer coolant widens the dry-cooling window</strong></h3>
<p>Usable coolant temperature at the rack buys ambient margin at the heat rejection plant. That is why the warm end of the range matters commercially.</p>
<p>NVIDIA’s <a href="https://docs.nvidia.com/dsx/maxlps/overview">DSX reference documentation</a> states that “at the rack, the TCS is designed for a 45°C supply design point.” That point, it adds, “can widen the opportunity for dry cooling and reduce cooling overhead when site and ambient conditions permit.” Note the loop: 45°C (113°F) is technology cooling supply to the cold plates, not facility water to the CDU.</p>
<p>The qualifier carries the engineering. A high TCS supply point raises the facility water temperature the CDU can work with, extending the hours a dry cooler carries the load. Whether it does at a given site depends on ambient conditions, CDU approach, exchanger sizing, and redundancy. NVIDIA’s own documentation concedes that an Arizona site “may need trim support for much of the year and mechanical cooling during the hottest conditions.”</p>
<p>Warm coolant is an opportunity to design for, not a guarantee of chiller-free operation.</p>
<h3><strong>Liquid cooling is not the same as waterless cooling</strong></h3>
<p>A closed IT-side loop says nothing about site water consumption. The heat rejection architecture decides that.</p>
<p>Uptime Institute puts it plainly: <a href="https://journal.uptimeinstitute.com/water-is-local-generalities-do-not-apply/">“water is consumed only in the heat rejection loop.”</a> A closed collection loop “consumes little (if any) water — even when serving DLC equipment.” LBNL’s <a href="https://escholarship.org/uc/item/32d6m0d1">2024 energy report</a> makes the point from the other side, describing an IT liquid cooling system on a waterside economizer as one that “consumes substantial amounts of water, like all evaporative cooling systems.”</p>
<p>Uptime’s guidance: water-cooled rejection is typically most energy-efficient where water is plentiful, while water-stressed sites “should prioritize dry free cooling and mechanical cooling modes.” Going dry spends fan energy, compressor energy on design days, and plot space instead of water. The cold plate decides none of it.</p>
<h3><strong>Heat reuse, and why the grade matters</strong></h3>
<p>Liquid cooling raises the temperature grade of recovered heat, which is what makes reuse worth considering. LBNL-affiliated authors report as much in a 2026 National Academy of Engineering article, <a href="https://datacenters.lbl.gov/publications/avoiding-waste-heat-through-ai"><em>Avoiding Waste Heat through AI Infrastructure Thermal Integration</em></a>. Advanced cooling raises the temperature of dissipated heat “from about 30°C (typical of air cooling) to more than 50°C,” roughly 86°F to more than 122°F.</p>
<p>Whether that heat gets reused is economic rather than thermal. It takes an offtaker within reach and a supply agreement both parties can carry, and the interface between them is another heat exchanger.</p>
<h2><strong>Plate versus shell-and-tube: what actually decides the selection</strong></h2>
<p>Plate technology is typically the preferred selection inside a liquid-to-liquid CDU. Shell-and-tube construction becomes a candidate further out in the facility infrastructure, and only where specific conditions justify it. This comparison is often written to reach a conclusion. It should be written to reach a selection basis.</p>
<h3><strong>Why plate exchangers suit the CDU duty</strong></h3>
<p>The CDU duty is a very close approach in a very small envelope, with clean, treated fluid on both sides. ASHRAE describes the exchanger as “typically a flat plate construction with nominal plate spacing ranging from 0.079 to 0.315 in. (2 to 8 mm).”</p>
<p>Commercial liquid-to-liquid CDUs are rated at 4–5°C (7–9°F) approach. Vertiv publishes 4°C ATD across its 600 kW, 1,350 kW, and 2,300 kW models; CoolIT publishes 5°C ATD for its <a href="https://www.coolitsystems.com/products-services/data-center-products/cooling-distribution-units/">row-based CHx units</a>. Corrugated plates deliver high turbulence and high surface area at low hold-up volume, which is what that specification demands. Tubular construction is not a practical way to hit that approach in that footprint.</p>
<p>The sharpest contrast sits within plate technology itself. CoolIT rates its liquid-to-air <a href="https://www.coolitsystems.com/cdu-product/ahx240/">AHx240</a> at 15°C (27°F) approach — roughly three times the approach, for rejecting to air instead of water. The fluid on the cold side matters more than the exchanger geometry.</p>
<h3><strong>Where shell-and-tube becomes a candidate</strong></h3>
<p>The selection opens up on the facility side and at the plant interfaces, where duty, fluid quality, and service life change the weighting. That is the region where <a href="/data-center-cooling-equipment/">custom-fabricated exchangers and vessels for data center cooling</a> are specified.</p>
