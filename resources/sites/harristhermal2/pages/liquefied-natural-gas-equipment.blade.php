    <div class="px-sec-head px-reveal">
      <div class="px-kicker">FAQs</div>
      <h2>LNG equipment questions.</h2>
    </div>
    <div class="px-faq">
<details><summary>What equipment does Harris Thermal fabricate for LNG facilities?</summary><div class="a"><p>Shell-and-tube heat exchangers, process coolers and heaters, condensers, replacement exchangers and tube bundles, ASME Section VIII pressure vessels, separators and knockout drums, accumulators, process vessels, absorber and scrubber columns, custom shop-fabricated tanks within our scope, and stainless and high-alloy equipment for low-temperature service. Harris Thermal fabricates equipment for integration into LNG processing and handling systems; pumps, valves, instrumentation, controls and complete packaged systems are supplied by others.</p></div></details>
<details><summary>Can Harris Thermal fabricate cryogenic tanks and pressure vessels?</summary><div class="a"><p>Yes, within Harris Thermal's qualified shop-fabricated capabilities and subject to the project's design temperature and pressure, material, code, fabrication, testing and transportation requirements. Equipment is shop-fabricated and shipped complete; Harris Thermal does not perform field erection, so facility-scale field-erected LNG storage tanks are outside this scope.</p></div></details>
<details><summary>What materials are used for low-temperature LNG service?</summary><div class="a"><p>Stainless steels including 304L and 316L, duplex stainless, AL-6XN, high-nickel alloys for contaminant-bearing streams, and carbon steel on structural and non-cryogenic duty. Low-temperature service brings its own impact-testing and weld-qualification requirements, and those follow the code and the project specification.</p></div></details>
