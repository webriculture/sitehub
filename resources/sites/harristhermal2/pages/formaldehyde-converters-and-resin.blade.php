      <div class="px-kicker">Process Technology</div>
      <h2>Converter configuration follows the process.</h2>
      <p>Formaldehyde is produced by more than one route, and the converter is not the same piece of equipment in each. Catalyst type, operating temperature, tube geometry, metallurgy and the heat-removal arrangement all change with the process technology the plant is built around.</p>
      <p>Harris Thermal fabricates to the design basis supplied by the producer, the EPC or the process licensor. We bring the fabrication and material judgement; the process design stays with the party that owns it.</p>
