<p>A procurement trap sits inside that table. Both S31803 and S32205 are sold as “2205” under EN designation 1.4462, but only S32205 carries the tightened nitrogen range and the higher PREN.</p>
<p>The 6% molybdenum superaustenitics are the usual step above duplex, and their advantage is structural as well as chemical. IMOA gives the ASME allowable stress for N08367 at 800°F (427°C) as 18 ksi against 9.6 ksi for Type 316 — nearly double, which translates into thinner walls for the same duty.</p>
<h2><strong>Nickel alloys: matching Hastelloy and Inconel to the acid</strong></h2>
<p>Nickel alloys read as three-element recipes. Nickel suppresses chloride SCC, chromium handles oxidizing media, molybdenum handles reducing acids and pitting. Copper, where present, is there for sulfuric acid.</p>
<p><a href="https://www.haynesintl.com/en/alloy/hastelloy-c-276/">Hastelloy C-276</a> (N10276) balances 16% chromium against 16% molybdenum with 4% tungsten, which is why it tolerates both acid types better than single-purpose alloys. Haynes publishes a critical pitting temperature of <strong>302°F (150°C)</strong> and a critical crevice temperature of <strong>131°F (55°C)</strong> in acidified 6% ferric chloride per ASTM G48. Its limit is hot oxidizing acid, and the published nitric acid data shows how sharply temperature dominates concentration: at 200°F (93°C), 70% nitric gives 2.62 mm/y, while at boiling even 60% nitric reaches 18.42 mm/y. Nitric service is a temperature question before it is a concentration question.</p>
<p><a href="https://www.haynesintl.com/en/alloy/hastelloy-b-3/">Hastelloy B-3</a> (N10675) is the specialist, at roughly 28.5% molybdenum with only 1.5% chromium, built for pure hydrochloric, hydrobromic, and sulfuric acids and other non-oxidizing acids. With essentially no chromium it has no oxidizing-acid capability, and oxidizing-ion contamination is the recognized restriction on B-type alloys: a B-3 bundle in hydrochloric service is at risk if an upstream unit puts ferric or cupric ion into the stream. Confirm the tolerance for a specific stream with the mill, because the margin is narrow.</p>
<p><a href="https://www.specialmetals.com/documents/technical-bulletins/monel-alloy-400.pdf">Monel 400</a> (N04400) holds a niche nothing else fills: Special Metals states it “offers exceptional resistance to hydrofluoric acid in all concentrations up to the boiling point.” Its weakness is stagnation. The same bulletin reports low corrosion rates in <em>flowing</em> seawater but crevice and pitting attack under stagnant conditions, which makes shell-side dead zones and idle-period layup a design concern rather than an operating detail.</p>
