<p>Two constraints deserve naming precisely. Gasketed plate units are bounded by the gasket — Kelvion publishes design pressures of roughly <a href="https://www.kelvion.com/products/plate-heat-exchangers/gasketed-plate-heat-exchangers">11 to 33 barg (160 to 480 psig) across its standard gasketed series</a>, with a welded-side variant to 64 barg (930 psig). <a href="https://www.kelvion.com/products/plate-heat-exchangers/brazed-plate-heat-exchangers">Brazed plate units</a> reach higher pressures but cannot be opened for mechanical cleaning — a real constraint wherever the cold side carries open-loop tower water.</p>
<p>The CDU exchanger and the facility interface are two different equipment problems that happen to sit twenty feet apart. Compactness governs one. Fouling, cleanability, mechanical robustness, and inspection access govern the other. Selection follows the duty, not a preference for a technology.</p>
<h2><strong>Materials and water chemistry: when an upgrade is justified</strong></h2>
<p>Material upgrades in cooling water service are justified by a documented corrosion mechanism, not by a general ranking of alloys.</p>
<p><strong>Open and closed loops fail differently.</strong> A closed facility loop with a corrosion inhibitor and controlled makeup can often run 300-series stainless, or carbon steel, successfully. The outcome depends on water chemistry, temperature, the treatment program, and system design rather than on the alloy alone.</p>
<p>An open tower loop concentrates dissolved solids by evaporation and drives chloride upward with every cycle of concentration. A makeup water analysis is not a loop water analysis.</p>
<p>Chloride, temperature, and crevice geometry together drive pitting and stress corrosion cracking in austenitic stainless. Where those conditions are credible, duplex and 6% molybdenum grades carry substantially higher <a href="https://www.imoa.info/download_files/stainless-steel/Stainless_Steel_Pipe.pdf">pitting resistance</a> than 304 or 316. One trap catches technically literate readers: residual <strong>chlorine</strong> and <strong>chloride</strong> are different specifications, routinely conflated, driving different mechanisms.</p>
<p><strong>Mixed metallurgy is the failure nobody owns.</strong> ASHRAE lists copper, low-zinc brasses, and passivated stainless as acceptable in both loops, and carbon steels in the facility loop only. Aluminum is conditional — “normally avoided in liquid cooling loops because of its potential as a galvanic corrosion catalyst of other metals,” though usable “provided there is proper surface treatment of the metal.”</p>
<p>Cold plates, manifolds, CDU internals, and facility piping are usually bought separately, so galvanic couples form at the interfaces between packages. The material is permissible; the coupling is what has to be engineered.</p>
<p><strong>Coolant choice is part of the design basis.</strong> A 25% propylene glycol solution appears throughout current AI deployment guidance; NVIDIA’s <a href="https://docs.nvidia.com/dgx-pdf/data-center-best-practices-with-dgx-b300-v1.pdf"><em>Data Center Best Practices with DGX B300</em></a> directs sites to have PG25 handling procedures in place where applicable, rather than mandating a composition. Glycol buys freeze protection and biological control at the cost of heat-transfer performance and pump head. Book those penalties at the start.</p>
<p>Most facility cooling water does not justify titanium, and most closed technology cooling loops do not justify anything beyond properly passivated stainless. Upgrades earn their cost where a documented mechanism exists — seawater or brackish makeup, high-chloride reclaimed water, aggressive treatment chemistry. Everywhere else, the money is better spent on treatment, filtration, and access for cleaning. The <a href="/2026/08/07/exotic-alloy-heat-exchangers-for-chemical-service-hastelloy-inconel-titanium-and-zirconium/">selection logic for corrosion-resistant alloys</a> is the same in cooling water as in chemical service: match the alloy to the mechanism.</p>
<h2><strong>Reliability, maintainability, and the load that has not arrived yet</strong></h2>
<p>An air-cooled hall carries a large buffer of conditioned air. A liquid-cooled rack does not, and that missing thermal mass changes the redundancy problem.</p>
<h3><strong>Thermal ride-through drops from minutes to seconds</strong></h3>
<p>Uptime Institute is direct about the consequence. Facilities below 10 kW per rack historically had <a href="https://journal.uptimeinstitute.com/lower-density-brings-server-efficiency-and-cooling-gains/">“several, sometimes tens of, minutes”</a> of ride-through. Cold plate systems “cannot tolerate loss of circulation for more than a few seconds.” ASHRAE TC 9.9 members made the same point <a href="https://www.ashrae.org/news/ashraejournal/ashrae-journal-podcast-episode-49">on the record</a>: lose flow to even a medium-power processor and “you’re talking seconds of time before you will have adverse thermal effects.”</p>
<p>That changes what redundancy has to accomplish. Uptime notes that <a href="https://journal.uptimeinstitute.com/liquid-cooling-will-not-outgrow-its-high-density-niche/">“acceptable ride-through time typically requires UPS power for CDU pumps, at a minimum.”</a> Generator start time is no longer inside the thermal budget.</p>
<p>Uptime’s <a href="https://uptimeinstitute.com/tiers">Tier definitions</a> frame the rest. Tier III adds concurrent maintainability — “no shutdowns when equipment needs maintenance or replacement.” Tier IV adds fault tolerance and requires continuous cooling. Uptime’s paper on <a href="https://uptimeinstitute.com/resources/asset/accredited-tier-designer-technical-paper-series-continuous-cooling">continuous cooling</a> goes further, recommending it “at densities beyond 4 kilowatts (kW)/rack, regardless of Tier” — a threshold today’s AI racks exceed by more than an order of magnitude.</p>
<p>For fabricated equipment in the heat path, the practical requirements follow from concurrent maintainability:</p>
<ul>
<li>
<p><strong>Isolation valves and bypasses</strong> at every exchanger, so a unit can be removed without draining the loop</p>
</li>
<li>
<p><strong>Pull space</strong> for a tube bundle, or plate-pack access clearance, designed into the layout rather than discovered during the first cleaning</p>
</li>
<li>
<p><strong>Vent, drain, and sample connections</strong> placed for real maintenance sequences and chemistry monitoring</p>
</li>
<li>
<p><strong>Instrumentation on both sides</strong> — inlet and outlet temperature, differential pressure — so fouling is trended rather than inferred after a capacity shortfall</p>
</li>
<li>
<p><strong>Redundant capacity sized honestly</strong> — an N+1 exchanger that cannot be isolated is not actually N+1</p>
</li>
</ul>
<h3><strong>Facility thermal infrastructure outlives the IT it serves</strong></h3>
<p>Servers and CDUs turn over on a hardware cycle. Facility piping, heat exchangers, pumps, electrical distribution, and heat rejection equipment do not.</p>
<p>The gap is widening. NVIDIA’s DGX SuperPOD reference architecture for GB200 NVL72 specifies 1.2 MW thermal design power across an eight-rack scalable unit, roughly 150 kW per rack. Its <a href="https://docs.nvidia.com/dgx-superpod/reference-architecture/scalable-infrastructure-rubinx86/latest/">Rubin-generation documentation</a> puts rack-level power at approximately 225 kW. The ASHRAE, NEMA, and PNNL framework states the designer’s problem directly. Balance “meeting current needs and factoring anticipated growth in computational complexity, energy consumption, and thermal loads.”</p>
<p>So facility-side equipment should be evaluated against plausible future load, not only the first deployment. That means deliberate provisions rather than blanket oversizing — headers sized for a later flow increase, exchanger surface and nozzles that accept a re-rate, space for an added unit, and hydraulic headroom for a future bundle’s pressure drop.</p>
<p>Oversizing alone is not the answer. An exchanger far off its design point fouls differently, controls poorly at low load, and costs more than it needs to. The framework’s own recommendation is modular “pay-as-you-grow” expansion in repeatable blocks.</p>
<h2><strong>Common mistakes in data center cooling equipment specification</strong></h2>
<p>Six specification errors recur often enough to be worth naming.</p>
<ul>
<li>
<p><strong>Treating the CDU as a hydraulic device.</strong> Its principal contribution is chemistry separation. Design the two loops as separate water quality domains, or the cold plates inherit the facility loop’s chloride, hardness, and particulate.</p>
</li>
<li>
<p><strong>Spending the whole approach budget in one place.</strong> Case temperature, TCS supply, CDU approach, facility water, tower approach, and ambient wet bulb form one chain. A generous margin at one link is usually borrowed from another.</p>
</li>
<li>
<p><strong>Selecting facility-side equipment on CDU logic.</strong> Compactness governs inside the cabinet. Fouling, cleanability, mechanical robustness, and inspection access govern where open-loop water, silt, and biological activity are present.</p>
</li>
<li>
<p><strong>Ignoring mixed metallurgy across procurement packages.</strong> Cold plates, manifolds, CDUs, and facility piping are often bought separately. Galvanic couples form at the interfaces nobody owns.</p>
</li>
<li>
<p><strong>Treating liquid cooling as waterless cooling.</strong> A closed IT loop can still reject heat through an evaporative tower. Water consumption is set at the heat rejection plant.</p>
</li>
<li>
<p><strong>Sizing the facility side for the first IT deployment only.</strong> Piping, exchangers, and heat rejection outlive several hardware generations.</p>
</li>
</ul>
<h2><strong>Specify the loop, the water, and the access</strong></h2>
<p>The most useful thing a project brings to a cooling equipment inquiry is not a heat exchanger type. It is a description of the duty complete enough that a fabricator or OEM can select one:</p>
<ul>
<li>
<p>Which loop the unit serves, and who controls its chemistry</p>
</li>
<li>
<p>Design and operating pressure and temperature on both sides</p>
</li>
<li>
<p>The approach the plant depends on</p>
</li>
<li>
<p>A real water analysis, including cycles of concentration and expected chloride</p>
</li>
<li>
<p>The fouling service, and how the unit will actually be cleaned</p>
</li>
<li>
<p>Code, examination, and testing requirements</p>
</li>
<li>
<p>Physical access for maintenance and eventual replacement</p>
</li>
</ul>
<p>Those answers settle whether the duty calls for a compact plate unit, a fabricated shell-and-tube exchanger, or a closed-loop skid — and which supplier should build it.</p>
