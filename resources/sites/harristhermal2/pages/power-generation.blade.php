<section class="px-block soft" id="faqs">
  <div class="ht-wrap">
    <div class="px-sec-head px-reveal">
      <div class="px-kicker">FAQs</div>
      <h2>Power generation equipment questions.</h2>
    </div>
    <div class="px-faq">
<details><summary>What equipment does Harris Thermal fabricate for power generation?</summary><div class="a"><p>Shell-and-tube heat exchangers including feedwater heaters and condensers, process and auxiliary coolers, replacement tube bundles and custom replacement exchangers, ASME Section VIII pressure vessels, separators, accumulators, surge and storage vessels, high-alloy process vessels, custom tanks, auxiliary cooling equipment, scrubber and emissions vessels, and evaporators and crystallizers. Harris Thermal fabricates equipment for integration into plant systems; it does not supply pumps, controls or complete packaged systems.</p></div></details>
<details><summary>Can Harris Thermal fabricate replacement heat exchangers and tube bundles?</summary><div class="a"><p>Yes, and it is a large part of the power work. Replacement exchangers can be built to the original envelope and nozzle geometry so the unit drops into existing piping and supports, re-tubed where the shell is sound, or re-rated for a duty above the original basis. We work from existing drawings, field measurements or reverse-engineered specifications. See our repairs, re-tubing and re-rating capability.</p></div></details>
<details><summary>What codes and standards does Harris Thermal build power equipment to?</summary><div class="a"><p>ASME Section VIII, Division 1 for pressure vessels, with the U-stamp where a code vessel is required; TEMA for shell-and-tube exchangers; applicable API standards for tanks and exchangers; and PED/CE or CRN where an international or Canadian project requires it. The applicable code follows the equipment scope and the project specification.</p></div></details>
<details><summary>Can Harris Thermal support nuclear and advanced reactor power projects?</summary><div class="a"><p>Yes, within qualified fabrication scope. Harris Thermal fabricates custom heat exchangers, ASME pressure vessels and other thermal equipment for nuclear and advanced power projects, and has an NQA-1 quality assurance program in place. Our nuclear page sets out the scope, the quality program and the project history in full.</p></div></details>
