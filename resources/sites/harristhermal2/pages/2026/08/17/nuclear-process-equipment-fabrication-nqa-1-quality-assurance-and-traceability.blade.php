<h2><strong>FAQs about NQA-1 and nuclear equipment fabrication</strong></h2>
<h3><strong>Is NQA-1 the same as the ASME Boiler and Pressure Vessel Code?</strong></h3>
<p>No. They govern different things. The BPVC is a design and construction code, setting allowable stresses, thickness rules, welding and examination requirements, and testing for the equipment itself. ASME NQA-1 is a nuclear quality assurance standard, setting requirements for the program under which the work is planned, controlled, verified, and documented. Equipment is designed and built to Section III or Section VIII; the program governing that work may be an NQA-1 program. NQA-1 contains no design rules, and no construction code contains a complete quality assurance program.</p>
<h3><strong>Does an ASME U-stamp mean a fabricator meets NQA-1?</strong></h3>
<p>No. A Certificate of Authorization and the Certification Mark show that a quality control system was accredited for construction under a specific Code section. RG 1.28, Revision 6 states that NRC recognition of the ASME Accreditation Program "applies only to the programmatic aspects of the QA programs," and that purchasers should confirm suppliers are effectively implementing their approved programs. An NQA-1 program is a separate and broader set of controls, evaluated on its own.</p>
<h3><strong>What equipment can be subject to NQA-1 requirements?</strong></h3>
<p>Any item or service affecting a safety function. That is determined by classification, not by equipment type. In practice it has included pressure vessels, shell-and-tube heat exchangers, condensers, evaporators, columns and towers, separators, tanks, piping and spools, and process skids and modular assemblies. It also covers supporting services such as nondestructive examination, heat treatment, and calibration. Non-safety-related equipment at the same facility may carry a reduced control set, selected NQA-1 requirements imposed by contract, or neither. The procurement documents govern.</p>
<h3><strong>Which edition of NQA-1 applies to a project?</strong></h3>
<p>Whichever edition the procurement documents invoke. For NRC-regulated work, RG 1.28, Revision 6 endorses Parts I and II of NQA-1-2017, NQA-1-2019, and NQA-1-2022, subject to stated exceptions. ASME has since published NQA-1-2024. On DOE work, 10 CFR Part 830 does not name the standard, so the edition arrives through contract. Confirm the edition and the applicable Requirements in writing before bidding.</p>
<h3><strong>Why is material traceability important in nuclear fabrication?</strong></h3>
<p>Because it is required, and because the alternative cannot be verified. Appendix B Criterion VIII requires identification maintained "by heat number, part number, serial number, or other appropriate means, either on the item or on records traceable to the item." Criterion VII requires documentary evidence of conformance to be available at the site before installation or use. Traceability is also the practical defense against counterfeit, fraudulent, and suspect items. NRC Information Notice 2008-04 documented counterfeit valves that reached a nuclear plant with documentation in hand, one of which ran eight months in a non-safety-related system before discovery.</p>

