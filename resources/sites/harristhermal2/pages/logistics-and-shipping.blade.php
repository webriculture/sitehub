<section class="px-block">
  <div class="ht-wrap">
    <div class="px-sec-head px-reveal"><div class="px-kicker">Where It Goes</div><h2>Across the United States, and to projects worldwide.</h2><p>We have shipped vessels 20 ft in outside diameter and evaporators over 100,000 pounds by truck and barge.</p></div>
    <div class="px-whys">
      <div class="px-why px-reveal"><h4>Domestic Shipments</h4><p>Equipment moves to customer sites across the United States, with carrier selection, routing, and delivery timing coordinated around each site's access and installation schedule.</p></div>
      <div class="px-why px-reveal"><h4>International Projects</h4><p>For projects outside the United States, we coordinate with the customer's freight forwarders and carriers so fabricated equipment reaches its destination port or job site.</p></div>
      <div class="px-why px-reveal"><h4>Oversized &amp; Heavy Loads</h4><p>Equipment beyond standard trailer dimensions or weight is identified early, so the transportation requirements it creates are built into the project schedule instead of discovered at shipment.</p></div>
